"""scripts/install_pre_push_hook.sh — the pre-push gate's installer, serialized (W-cd77f476).

Every interactive shell installs the pre-push hook (scripts/wsl_startup_hook.sh). pre-commit writes
the hook in place, so two shells starting together could read each other's half-written file as a
foreign hook and move it to `pre-push.legacy`; from then on every push failed "installed in
migration mode". Measured before the fix: 8 concurrent installs left a legacy in 16 of 20 trials.
The same in-place rewrite briefly leaves an EMPTY hook, which git runs as a pass, so the installer
also leaves a current hook alone.
"""

from __future__ import annotations

import fcntl
import os
import subprocess
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

HUB = Path(__file__).resolve().parents[1]
INSTALLER = HUB / "scripts" / "install_pre_push_hook.sh"
PRE_COMMIT = HUB / ".venv" / "bin" / "pre-commit"
ID_LINE = "# ID: 138fd403232d2ddd5efb44317e38bf03"


def _repo(tmp_path: Path, name: str = "repo") -> Path:
    repo = tmp_path / name
    subprocess.run(["git", "init", "-q", str(repo)], check=True)
    (repo / ".pre-commit-config.yaml").write_text(
        (HUB / ".pre-commit-config.yaml").read_text(encoding="utf-8"), encoding="utf-8"
    )
    return repo


def _install(root: Path, bin_path: Path = PRE_COMMIT) -> subprocess.CompletedProcess:
    env = {k: v for k, v in os.environ.items() if not k.startswith("GIT_")}
    env.update(
        INSTALL_PRE_PUSH_TEST="1",
        INSTALL_PRE_PUSH_ROOT=str(root),
        INSTALL_PRE_PUSH_BIN=str(bin_path),
    )
    return subprocess.run(
        ["bash", str(INSTALLER)], capture_output=True, text=True, env=env, check=False, timeout=120
    )


def _hooks(repo: Path) -> Path:
    return repo / ".git" / "hooks"


def test_concurrent_installs_never_leave_a_legacy_copy(tmp_path: Path) -> None:
    for trial in range(6):
        repo = _repo(tmp_path, f"r{trial}")
        with ThreadPoolExecutor(max_workers=8) as pool:
            results = list(pool.map(_install, [repo] * 8))
        assert all(r.returncode == 0 for r in results), [r.stderr for r in results]
        assert not (_hooks(repo) / "pre-push.legacy").exists(), f"trial {trial}: a legacy was left"
        assert ID_LINE in (_hooks(repo) / "pre-push").read_text(encoding="utf-8")


def test_a_held_lock_skips_the_install_without_touching_the_hook(tmp_path: Path) -> None:
    repo = _repo(tmp_path)
    _hooks(repo).mkdir(parents=True, exist_ok=True)
    with open(_hooks(repo) / ".pre-push-install.lock", "w") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        result = _install(repo)
        assert result.returncode == 0, result.stderr
        assert not (_hooks(repo) / "pre-push").exists()  # the holder installs; this run did not
    assert _install(repo).returncode == 0
    assert ID_LINE in (_hooks(repo) / "pre-push").read_text(encoding="utf-8")


def test_a_current_hook_is_not_rewritten(tmp_path: Path) -> None:
    repo = _repo(tmp_path)
    assert _install(repo).returncode == 0
    before = os.stat(_hooks(repo) / "pre-push")
    assert _install(repo).returncode == 0
    after = os.stat(_hooks(repo) / "pre-push")
    assert (after.st_ino, after.st_mtime_ns) == (before.st_ino, before.st_mtime_ns)


def test_a_self_copy_or_empty_legacy_is_healed(tmp_path: Path) -> None:
    for name, payload in (("self", None), ("empty", b"")):
        repo = _repo(tmp_path, name)
        assert _install(repo).returncode == 0
        legacy = _hooks(repo) / "pre-push.legacy"
        legacy.write_bytes((_hooks(repo) / "pre-push").read_bytes() if payload is None else payload)
        legacy.chmod(0o755)  # the live shape: an executable legacy is what breaks every push
        result = _install(repo)
        assert result.returncode == 0, (name, result.stderr)
        assert not legacy.exists(), name
        assert ID_LINE in (_hooks(repo) / "pre-push").read_text(encoding="utf-8")


def test_a_foreign_legacy_is_kept_and_reported(tmp_path: Path) -> None:
    repo = _repo(tmp_path)
    _hooks(repo).mkdir(parents=True, exist_ok=True)
    # a hand-written wrapper whose COMMENT quotes pre-commit's banner is still not pre-commit's
    foreign = (
        "#!/bin/sh\n# wraps the File generated by pre-commit: https://pre-commit.com shim\nexit 0\n"
    )
    legacy = _hooks(repo) / "pre-push.legacy"
    legacy.write_text(foreign, encoding="utf-8")
    result = _install(repo)
    assert result.returncode == 3 and "migration mode" in result.stderr
    assert legacy.read_text(encoding="utf-8") == foreign


def test_a_set_core_hookspath_is_refused(tmp_path: Path) -> None:
    repo = _repo(tmp_path)
    subprocess.run(["git", "-C", str(repo), "config", "core.hooksPath", "elsewhere"], check=True)
    result = _install(repo)
    assert result.returncode != 0 and "core.hooksPath" in result.stderr
    assert not (_hooks(repo) / "pre-push").exists()


def test_a_missing_pre_commit_is_a_silent_no_op(tmp_path: Path) -> None:
    repo = _repo(tmp_path)
    result = _install(repo, tmp_path / "no-venv" / "pre-commit")
    assert result.returncode == 0 and result.stderr == ""
    assert not (_hooks(repo) / "pre-push").exists()


def test_a_worktree_installs_into_the_shared_hooks(tmp_path: Path) -> None:
    repo = _repo(tmp_path)
    subprocess.run(
        [
            "git",
            "-C",
            str(repo),
            "-c",
            "user.email=t@t",
            "-c",
            "user.name=t",
            "commit",
            "-q",
            "--allow-empty",
            "--no-verify",
            "-m",
            "x",
        ],
        check=True,
    )
    wt = tmp_path / "wt"
    subprocess.run(["git", "-C", str(repo), "worktree", "add", "-q", str(wt)], check=True)
    assert _install(wt).returncode == 0
    assert ID_LINE in (_hooks(repo) / "pre-push").read_text(encoding="utf-8")
    assert (wt / ".git").is_file()  # the worktree's gitfile is untouched


def test_the_startup_hook_installs_through_the_serialized_installer() -> None:
    src = (HUB / "scripts" / "wsl_startup_hook.sh").read_text(encoding="utf-8")
    assert "scripts/install_pre_push_hook.sh" in src
    assert 'pre-commit" install -t pre-push' not in src


def test_a_hook_without_its_exec_bit_is_reinstalled(tmp_path: Path) -> None:
    # git silently SKIPS a non-executable hook, so "current" must include +x
    repo = _repo(tmp_path)
    assert _install(repo).returncode == 0
    hook = _hooks(repo) / "pre-push"
    hook.chmod(0o644)
    assert _install(repo).returncode == 0
    assert os.access(hook, os.X_OK)


def test_a_foreign_legacy_with_an_id_shaped_line_is_kept(tmp_path: Path) -> None:
    # only pre-commit's REAL template hashes mark its own script, not any 32-hex comment
    repo = _repo(tmp_path)
    _hooks(repo).mkdir(parents=True, exist_ok=True)
    foreign = "#!/bin/sh\n# ID: 0123456789abcdef0123456789abcdef\nexit 0\n"
    legacy = _hooks(repo) / "pre-push.legacy"
    legacy.write_text(foreign, encoding="utf-8")
    assert _install(repo).returncode == 3
    assert legacy.read_text(encoding="utf-8") == foreign


def test_a_dangling_symlink_legacy_is_removed(tmp_path: Path) -> None:
    repo = _repo(tmp_path)
    _hooks(repo).mkdir(parents=True, exist_ok=True)
    legacy = _hooks(repo) / "pre-push.legacy"
    legacy.symlink_to(tmp_path / "gone")
    assert _install(repo).returncode == 0
    assert not legacy.is_symlink() and not legacy.exists()


def test_a_failing_install_says_so_and_exits_1(tmp_path: Path) -> None:
    repo = _repo(tmp_path)
    fake = tmp_path / "bin" / "pre-commit"
    fake.parent.mkdir()
    fake.write_text("#!/bin/sh\nexit 2\n", encoding="utf-8")
    fake.chmod(0o755)
    result = _install(repo, fake)
    assert result.returncode == 1 and "install -t pre-push failed" in result.stderr


def test_every_other_legacy_shape_lands_on_the_right_side(tmp_path: Path) -> None:
    # healed: a symlink to pre-commit's own script, a NON-executable self-copy;
    # kept and reported: a directory (never pre-commit's, and never deleted by an installer)
    for shape in ("symlink-to-ours", "non-exec-self", "directory"):
        repo = _repo(tmp_path, shape)
        assert _install(repo).returncode == 0
        hooks = _hooks(repo)
        legacy = hooks / "pre-push.legacy"
        if shape == "symlink-to-ours":
            ours = tmp_path / f"{shape}-copy"
            ours.write_bytes((hooks / "pre-push").read_bytes())
            legacy.symlink_to(ours)
        elif shape == "non-exec-self":
            legacy.write_bytes((hooks / "pre-push").read_bytes())
            legacy.chmod(0o644)
        else:
            legacy.mkdir()
        result = _install(repo)
        if shape == "directory":
            assert result.returncode == 3 and legacy.is_dir(), (shape, result.stderr)
        else:
            assert result.returncode == 0, (shape, result.stderr)
            assert not legacy.exists() and not legacy.is_symlink(), shape
