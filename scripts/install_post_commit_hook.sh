#!/usr/bin/env bash
# AFTER-EDIT: docs/workstation/hooks-index.md, tests/enforcement/test_governance_sync_postcommit.py, tests/test_merge_sync.py, tests/test_workitem_merge_driver.py
#
# Installs the hub's POST-COMMIT and POST-MERGE hooks as PLAIN git hooks that run
# scripts/governance_sync_postcommit.sh directly — never pre-commit's post-commit stage. pre-commit
# stashes every unstaged change in the tree around each `run` and restores with a tree-wide
# `git checkout -- .` (pre_commit/staged_files_only.py), so for the ~60 s the fleet sync took, any edit a sibling session made to any tracked file was silently
# reverted (mail 01M3492KY09K6DP47Z21XVM2SH, D-369). Same shape and reason as the commit-msg shim
# (scripts/check_commit_trailers.py --install). Idempotent; replaces pre-commit's generated
# post-commit/post-merge shims; refuses any other foreign hook. Re-run by scripts/wsl_startup_hook.sh
# on every interactive shell.
set -euo pipefail

ROOT=/opt/fabrik
# Test seam, honoured ONLY under the explicit sentinel (the same pattern as the wrapper's SYNC_CMD).
if [ "${GOVERNANCE_SYNC_TEST:-}" = "1" ] && [ -n "${GOVERNANCE_SYNC_ROOT:-}" ]; then
  ROOT="$GOVERNANCE_SYNC_ROOT"
fi

# git reads hooks from core.hooksPath when it is set, so a hook written to .git/hooks would never fire —
# refuse loudly rather than install something inert (pre-commit's own installer refuses the same way).
if hp="$(git -C "$ROOT" config --get core.hooksPath)"; then
  echo "install_post_commit_hook: core.hooksPath is set ($hp) — git would never run .git/hooks/post-commit or post-merge; unset it first" >&2
  exit 1
fi

# --git-common-dir resolves to the SHARED git dir from a worktree too, so every checkout gets these hooks.
common="$(cd "$ROOT" && cd "$(git rev-parse --git-common-dir)" && pwd)"
MARK="Installed by scripts/install_post_commit_hook.sh"
# Two hooks, one script: post-commit syncs HEAD's own paths; post-merge syncs what a merge brought in,
# because `git merge` (fast-forward or --no-ff) fires no post-commit hook and a worktree commit syncs
# nothing, so a merge is the only way a worktree's governance change reaches the fleet (spec
# 2026-09-29-hub-worktree-cutover-design § D3 (b)).
HOOKS="post-commit post-merge"

# Refuse BEFORE writing anything, so a foreign hook on either name never leaves a half-install.
for name in $HOOKS; do
  target="$common/hooks/$name"
  if [ -e "$target" ] && ! grep -qF "$MARK" "$target" && ! grep -qF "File generated by pre-commit" "$target"; then
    echo "install_post_commit_hook: refusing to replace a foreign $target — move it aside first" >&2
    exit 1
  fi
done

mkdir -p "$common/hooks"
tmp=""
trap 'rm -f "$tmp"' EXIT   # a failed write never leaves a stray temp file in the shared hooks dir
for name in $HOOKS; do
  target="$common/hooks/$name"
  arg=""
  [ "$name" = post-merge ] && arg=" post-merge"
  tmp="$(mktemp "$common/hooks/.$name.XXXXXX")"
  cat > "$tmp" <<SHIM
#!/bin/sh
# $MARK — a plain git hook, deliberately NOT pre-commit's $name stage (see that script's header).
# git ignores a $name hook's exit status, so this shim can never block a commit or a merge.
exec bash "$ROOT/scripts/governance_sync_postcommit.sh"$arg
SHIM
  chmod 755 "$tmp"
  mv -f "$tmp" "$target"   # atomic: a commit running right now reads either the old hook or the new one
  tmp=""

  # `pre-commit install -t <name>` keeps a hook it did not write as <name>.legacy (migration mode).
  # Once the plain hook is back, a legacy copy of it is dead weight nobody runs — remove only our own.
  legacy="$common/hooks/$name.legacy"
  if [ -f "$legacy" ] && grep -qF "$MARK" "$legacy"; then rm -f "$legacy"; fi
done

# The work-item merge driver (W-c230cb2e): `.gitattributes` maps .fabrik/work/W-*.json to `workitem`,
# and a hand merge, rebase or cherry-pick in any hub worktree then merges an item key-wise with
# `work.py merge-item` — the tree's OWN copy, since git runs the driver at the worktree top level.
# Any non-zero exit (a key both sides changed, a work.py without the verb, no python3) falls back to
# git's text merge, so a conflict keeps its markers and never picks a side. `-X ours|theirs` reach no
# custom driver. merge_request.py resolves item conflicts on its own (D-988) and needs none of this.
DRIVER='python3 scripts/work.py merge-item %O %A %B || git merge-file --marker-size %L -L ours -L base -L theirs %A %O %B'
# The ledger merge driver (W-53360407, D-1386): `.gitattributes` maps the five root ledgers to `ledger`,
# and `merge_request.py merge-ledger` resolves concurrent insertions with the merge owner's own
# resolver; an edit of a landed line, a duplicate D-id or any failure falls back to git's markers.
LEDGER_DRIVER='python3 scripts/merge_request.py merge-ledger %O %A %B %P || git merge-file --marker-size %L -L ours -L base -L theirs %A %O %B'
# Written only when it differs: a same-value `git config` still replaces the shared file under
# config.lock, and this runs on every shell, racing every sibling's own config write. A write that
# fails (a sibling holds the lock, or a stale lock) is reported and the run goes on, so the
# attributes below are still copied; the non-zero exit is what wsl_startup_hook.sh prints.
rc=0
set_config() {
  [ "$(git -C "$ROOT" config --get-all "$1" 2>/dev/null)" = "$2" ] && return 0
  git -C "$ROOT" config --replace-all "$1" "$2" ||
    { echo "install_post_commit_hook: could not set $1 — that merge driver is not registered; the next shell retries" >&2; rc=1; }
}
set_config merge.workitem.name "work.py merge-item (key-wise work-item merge)"
set_config merge.workitem.driver "$DRIVER"
set_config merge.ledger.name "merge_request.py merge-ledger (ledger insertions)"
set_config merge.ledger.driver "$LEDGER_DRIVER"
# git reads .gitattributes from the tree as it was BEFORE the merge, so a branch cut before the file
# existed would get no driver on the merge that brings it in; <common>/info/attributes applies to
# every worktree at once. Its merge=workitem lines are a block this installer OWNS, rebuilt from
# .gitattributes (the mapping's one hand-written home) on every run — so a line removed there leaves
# here too — and replaced atomically only when it changed; every other line is kept.
info="$common/info/attributes"
BEGIN_MARK="# BEGIN work-item merge driver — managed by scripts/install_post_commit_hook.sh"
END_MARK="# END work-item merge driver"
want=""
[ -f "$ROOT/.gitattributes" ] &&
  want="$(grep -E '^[[:space:]]*[^#[:space:]].*[[:space:]]merge=(workitem|ledger)([[:space:]]|$)' "$ROOT/.gitattributes" || true)"
current=""
[ -f "$info" ] && current="$(cat "$info")"
# A block's lines are dropped only when its END arrives; an unclosed BEGIN (a hand-trimmed END)
# keeps every line after it — up to the next BEGIN too, which proves the first was never closed — so a
# person's attribute lines are never deleted.
kept="$(printf '%s\n' "$current" | awk -v b="$BEGIN_MARK" -v e="$END_MARK" '
  $0 == b { for (i = 1; i <= n && inblk; i++) print held[i]; inblk = 1; n = 0; next }
  inblk && $0 == e { inblk = 0; next }
  inblk { held[++n] = $0; next }
  { print }
  END { for (i = 1; i <= n && inblk; i++) print held[i] }')"
new="$kept"
[ -n "$want" ] && new="${kept:+$kept
}$BEGIN_MARK
$want
$END_MARK"
if [ "$new" != "$current" ]; then
  mkdir -p "$common/info"
  tmp="$(mktemp "$common/info/.attributes.XXXXXX")"
  if [ -n "$new" ]; then printf '%s\n' "$new" > "$tmp"; else : > "$tmp"; fi
  chmod 644 "$tmp"
  mv -f "$tmp" "$info"
  tmp=""
fi
exit "$rc"
