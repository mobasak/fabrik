#!/usr/bin/env python3
# AFTER-EDIT: docs/reference/kilo/STT_SELECTION.md
"""Phase B ranker — STT. Emits docs/reference/kilo/STT_SELECTION.md."""

from __future__ import annotations

import datetime as _dt
import sqlite3
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from rank_coding_subagents import _atomic_write, _safe_md_id  # noqa: E402
from suggest_model import _rank_service_type  # noqa: E402

DB_PATH = Path(__file__).parent / "kilo_agents.db"
OUT_PATH = Path(__file__).parent.parent.parent / "docs" / "reference" / "kilo" / "STT_SELECTION.md"
_BENCH_MINUTES = 60.0


def _render(rows: list[dict]) -> str:
    today = _dt.date.today().isoformat()
    lines = [
        f"Last refresh: {today}",
        "",
        "# STT Selection — Pareto-ranked at 60 minutes",
        "",
        "Auto-generated by `rank_stt.py` (daily via `daily_refresh.sh`). Rows come from",
        "`agents WHERE service_type='stt' AND reachable_with_existing_keys=1`; cost is",
        "normalized to a 60-minute workload; Pareto frontier keeps rows not dominated on",
        "(lower cost, higher quality_elo).",
        "",
        "| # | Model | Provider | Cost @60 min (USD) | quality_elo |",
        "|---|---|---|---:|---:|",
    ]
    for i, r in enumerate(rows[:10], 1):
        q = f"{r['quality_elo']:.0f}" if r.get("quality_elo") else "—"
        lines.append(
            f"| {i} | `{_safe_md_id(r['id'])}` | {r['provider']} | ${r['cost_usd']:.4f} | {q} |"
        )
    if not rows:
        lines.append("| — | _no accessible STT rows_ | — | — | — |")
    return "\n".join(lines) + "\n"


def main() -> int:
    conn = sqlite3.connect(DB_PATH)
    try:
        rows = _rank_service_type(conn, "stt", minutes=_BENCH_MINUTES)
    finally:
        conn.close()
    _atomic_write(OUT_PATH, _render(rows))
    print(f"wrote {OUT_PATH} ({len(rows)} rows on Pareto frontier)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
