#!/usr/bin/env python3
# AFTER-EDIT: docs/reference/kilo/TRANSLATION_SELECTION.md
"""Phase B ranker — Translation. Emits docs/reference/kilo/TRANSLATION_SELECTION.md."""

from __future__ import annotations

import datetime as _dt
import sqlite3
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from suggest_model import _rank_service_type  # noqa: E402
from rank_coding_subagents import _atomic_write, _safe_md_id  # noqa: E402

DB_PATH = Path(__file__).parent / "kilo_agents.db"
OUT_PATH = Path(__file__).parent.parent.parent / "docs" / "reference" / "kilo" / "TRANSLATION_SELECTION.md"
_BENCH_CHARS = 100_000


def _render(rows: list[dict]) -> str:
    today = _dt.date.today().isoformat()
    lines = [
        f"Last refresh: {today}",
        "",
        "# Translation Selection — Pareto-ranked at 100 000 chars",
        "",
        "Auto-generated by `rank_translation.py` (daily via `daily_refresh.sh`). Rows come",
        "from `agents WHERE service_type='translation' AND reachable_with_existing_keys=1`;",
        "cost is normalized to a 100 000-char workload; Pareto frontier keeps rows not",
        "dominated on (lower cost, higher quality_elo).",
        "",
        "| # | Model | Provider | Cost @100 000 chars (USD) | quality_elo |",
        "|---|---|---|---:|---:|",
    ]
    for i, r in enumerate(rows[:10], 1):
        q = f"{r['quality_elo']:.0f}" if r.get("quality_elo") else "—"
        lines.append(
            f"| {i} | `{_safe_md_id(r['id'])}` | {r['provider']} | ${r['cost_usd']:.4f} | {q} |"
        )
    if not rows:
        lines.append("| — | _no accessible translation rows_ | — | — | — |")
    return "\n".join(lines) + "\n"


def main() -> int:
    conn = sqlite3.connect(DB_PATH)
    try:
        rows = _rank_service_type(conn, "translation", chars=_BENCH_CHARS)
    finally:
        conn.close()
    _atomic_write(OUT_PATH, _render(rows))
    print(f"wrote {OUT_PATH} ({len(rows)} rows on Pareto frontier)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
