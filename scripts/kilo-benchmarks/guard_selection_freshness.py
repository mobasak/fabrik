#!/usr/bin/env python3
# AFTER-EDIT: autocommit_pipeline_outputs.sh (consumes this filter) | tests/test_guard_selection_freshness.py
"""Freshness filter for the pipeline auto-commit: never let a generated doc go BACKWARDS.

The auto-commit stages whatever the worktree holds. That is fine for a doc the pipeline just
regenerated — and wrong for a STALE copy, because committing it silently REVERTS a newer one.

Measured incident (2026-08-29, found 2026-09-02 while tracing an apparent 155->6 row loss in
``TASK_SUBAGENT_SELECTION.md``):

  01:27  ec05a490  the ranking's aggregation is FIXED (n had been double-counting the
                   `status='scored'` delta rows `set_quality` writes, so every scored run
                   counted twice)
  01:56  cfff4744  the doc is regenerated correctly — `Last refresh: 2026-08-29`, spec n=6
  06:01  8ec46c62  the auto-commit lands a doc reading `Last refresh: 2026-08-19` with the
                   OLD inflated spec n=155, under a message claiming "regenerated"

Nothing was deleted — but for four days `pick_models` read a ranking generated by a bug that had
already been fixed, and the commit message asserted the opposite. That is the failure this filter
ends: a doc whose own `Last refresh:` line is OLDER than the committed one is DROPPED from the
stage list and reported loudly, so the auto-commit can add and correct but never rewind.

Contract: reads candidate paths on argv, prints the SAFE ones to stdout (one per line), warns on
stderr for each drop. FAIL-OPEN — a path with no refresh line on either side, an unreadable file,
or any git error is KEPT (the pipeline's job is to publish; this filter only blocks a proven
regression). Always exits 0, like its sibling ``stage_ai_rule_renders.py``.
"""

from __future__ import annotations

import os
import re
import subprocess
import sys
from pathlib import Path

# the hub is the only real caller; the env override exists so the CLI path itself is testable
# against a throwaway repo (a test that can only assert "exit 0" proves nothing about the filter)
REPO = Path(os.environ.get("GUARD_REPO") or "/opt/fabrik")
# the generators emit this verbatim as the first line; `_fmt` in rank_task_subagents.py owns it
_REFRESH = re.compile(r"^Last refresh:\s*(\d{4}-\d{2}-\d{2})\s*$", re.M)


def refresh_date(text: str) -> str | None:
    """The doc's own `Last refresh: YYYY-MM-DD`, or None when it carries none.

    ISO dates compare correctly as strings, so no date parsing is needed — and a malformed
    date simply fails the regex and fail-opens rather than raising.
    """
    m = _REFRESH.search(text or "")
    return m.group(1) if m else None


def head_text(rel: str, repo: Path = REPO) -> str | None:
    """The committed version of ``rel``, or None when it is new/unreadable (→ fail-open KEEP)."""
    try:
        p = subprocess.run(
            ["git", "-C", str(repo), "show", f"HEAD:{rel}"],
            capture_output=True, text=True, timeout=30,
        )
    except Exception:
        return None
    return p.stdout if p.returncode == 0 else None


def is_regression(rel: str, repo: Path = REPO) -> tuple[bool, str]:
    """(True, why) only when BOTH sides carry a refresh date and the worktree's is OLDER."""
    try:
        work = (repo / rel).read_text(encoding="utf-8", errors="ignore")
    except OSError:
        return False, ""  # unreadable → not our call to block
    committed = head_text(rel, repo)
    if committed is None:
        return False, ""  # new file → nothing to rewind
    w, h = refresh_date(work), refresh_date(committed)
    if w is None or h is None:
        return False, ""  # not a dated generator output → out of scope
    if w < h:
        return True, f"worktree says {w}, HEAD already has {h}"
    return False, ""


def main(paths: list[str]) -> int:
    for rel in paths:
        regressed, why = is_regression(rel)
        if regressed:
            print(
                f"[freshness-guard] DROP {rel}: committing it would REVERT the doc ({why}). "
                "The pipeline did not regenerate it this run — re-run the generator, or commit "
                "it deliberately by hand if the older content is genuinely wanted.",
                file=sys.stderr,
            )
            continue
        print(rel)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
