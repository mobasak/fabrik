#!/usr/bin/env python3
# AFTER-EDIT: autocommit_pipeline_outputs.sh (consumes this filter) | tests/test_guard_selection_freshness.py
"""Freshness filter for the pipeline auto-commit: never let a generated doc go BACKWARDS.

The auto-commit stages whatever the worktree holds. That is fine for a doc the pipeline just
regenerated — and wrong for a STALE copy, because committing it silently REVERTS a newer one.

Measured incident (2026-08-29, found 2026-09-02 while tracing an apparent 155->6 row loss in
``TASK_SUBAGENT_SELECTION.md``):

  01:27  ec05a490  the ranking's aggregation is FIXED (n had been double-counting the
                   `status='scored'` delta rows `set_quality` writes, so every scored run
                   counted twice)
  01:56  cfff4744  the doc is regenerated correctly — `Last refresh: 2026-08-29`, spec n=6
  06:01  8ec46c62  the auto-commit lands a doc reading `Last refresh: 2026-08-19` with the
                   OLD inflated spec n=155, under a message claiming "regenerated"

Nothing was deleted — but for four days `pick_models` read a ranking generated by a bug that had
already been fixed, and the commit message asserted the opposite.

Contract: reads candidate paths on argv, prints the SAFE ones to stdout (one per line), warns on
stderr for each drop. FAIL-OPEN — no parseable header date on either side, a new file, an
unreadable file, or any git error KEEPS the path (this is a PUBLISHER: a wrong DROP silently stops
a doc reaching ~46 repos, which is worse than the staleness it guards). Exits 0 on success like its
sibling ``stage_ai_rule_renders.py``; a genuine crash exits non-zero so the caller can fall back.

⚠️ COVERAGE IS PARTIAL, AND THE DENOMINATOR IS COUNTED, NOT ESTIMATED (review 2026-09-02,
findings 5 + 8 — the first statement of this paragraph got BOTH halves wrong). Measured by
grepping the three header shapes across the real stage list: **7 of 14 static paths** and **7 of
11 ai-render packs** carry a date and are guarded. The 7 undated static paths —
`docs/CAPABILITIES.md`, `capabilities.json`, `docs/traycer/kilo_selected_agents.md`,
`KILO_MODEL_CAPABILITIES.md`, `KILO_AGENT_SELECTION_GUIDE.md`, `claude_p_cost.json`, `claude_usage_daily.json`
— and the 4 undated packs fail open by construction. ⚠️ The static count is GRADED, not asserted: it first read a count one too high because it
counted a `scripts/service_catalog.json` line a sibling held uncommitted in the worktree and never
landed — a denominator read off a shared tree instead of off HEAD. The wiring test
`test_the_docstring_denominator_matches_the_real_stage_list` re-derives both numbers from the
script itself and fails when the stage list moves.
"""

from __future__ import annotations

import os
import re
import subprocess
import sys
from datetime import date, datetime
from pathlib import Path

# The repo to compare against. The caller (`autocommit_pipeline_outputs.sh`) has already `cd`'d to
# its own `FABRIK_ROOT` and passes it explicitly; CWD is the fallback. ⚠️ NEVER hardcode
# `/opt/fabrik` here — the script honours `FABRIK_ROOT` and its own comments anticipate running in
# another checkout, so a hardcoded root made the guard inspect the WRONG repo, fail open, and let
# the exact 2026-08-29 incident reproduce with the fix installed (review 2026-09-02, finding 1).
REPO = Path(os.environ.get("GUARD_REPO") or os.getcwd())

# The three header shapes the pipeline's generators actually emit. `Last refresh:` is
# rank_task_subagents.py; `Last content verification:` is the ai-render packs
# (stage_ai_rule_renders.py:40) — the FLEET-SYNCED half, highest blast radius; `**Generated:**` is
# CODING_SUBAGENT_SELECTION.md, the incident doc's direct sibling. NOT anchored with `\s*$`: the
# sibling checker (check_daily_refresh_freshness.py:63) does not anchor either, and demanding a
# bare line meant any trailing text silently switched the guard OFF with no signal (finding 6).
# ⚠️ `[ \t]*`, NOT `\s*`: `\s` matches newlines, so `"Last refresh:\n\n2020-01-01"` bound a bare
# label line to whatever dated line followed it — a template placeholder or a truncated write would
# have been read as a real header (found 2026-09-02, round 2 late finder).
_HEADERS = re.compile(
    r"^(?:Last refresh:|Last content verification:|\*\*Generated:\*\*)[ \t]*(\d{4}-\d{2}-\d{2})",
    re.M,
)
# ⚠️ NO SKEW TOLERANCE — a 1-day allowance was added and then WITHDRAWN (review 2026-09-02,
# closing sweep finding 2). Its stated rationale was false: `is_regression` compares two dates
# written by the SAME generator (`rank_task_subagents.py:1225`, `date.today()` on both sides), so
# the UTC monitor and the `date -u` commit subject never enter the comparison — there is no
# cross-convention skew to absorb. And the cost was real: the generator runs DAILY, so "one day
# behind" is "exactly one generation behind" — the MOST likely rewind, not an edge case. A
# `git checkout HEAD~1 -- <doc>`, a rebase, or a stash-pop restoring yesterday's copy would have
# been silently KEPT and re-committed. The 2026-08-29 incident itself began as a one-day rewind.
_SKEW_DAYS = 0
# the generators emit their header within the first few lines; see refresh_date for the measured
# positions. Bounding the scan is what stops a quoted header being read as the real one.
_HEAD_LINES = 25


def refresh_date(text: str) -> date | None:
    """The doc's own generated-on date, or None when it carries none / it is not a real date.

    Returns a ``date``, not a string: a shape-only regex accepted ``2026-13-45``, which sorts
    above every real 2026 date and would have pinned the guard permanently closed against every
    later regeneration (finding 12). Calendar-validating turns that into a fail-open instead.
    """
    # ⚠️ HEAD-BOUNDED **AND AMBIGUITY-CHECKED**. The bound alone was never sufficient: it excludes a
    # quoted header BELOW line 25, and does nothing about one ABOVE the real header inside the window.
    # An earlier version of this comment claimed "bounding the scan is what stops a quoted header
    # being read as the real one" — that was FALSE for the in-bound case, which is the reachable one.
    # The bound plus the distinct-date check below is what actually closes it. Measured header positions across the real generators: line 1 (TASK_SUBAGENT,
    # TTS/STT/TRANSLATION/IMAGE_GEN), line 3 (CODING_SUBAGENT `**Generated:**`), lines 14-16 (the
    # ai-render packs' `Last content verification:`). 25 lines clears all of them with room and
    # still excludes any prose body. (Review 2026-09-02, findings 13 + own probe.)
    head = "\n".join((text or "").lstrip("﻿").splitlines()[:_HEAD_LINES])
    # ⚠️ AMBIGUITY FAILS OPEN. `search` took the FIRST hit, so a fenced format example ABOVE the real
    # header won and the guard DROPPED a fresh doc — the dangerous direction, since a wrong DROP
    # silently stops a doc reaching ~46 repos AND the alert tells the operator to "re-run the
    # generator", which cannot help. The head bound never prevented this: it only excludes examples
    # BELOW line 25. Reproduced 2026-09-02 (round 2 late finder): HEAD 2026-09-01, worktree carrying a
    # quoted `Last refresh: 2020-01-01` at line 4 and its real `2026-09-02` at line 6 → DROP.
    dates = {m.group(1) for m in _HEADERS.finditer(head)}
    if len(dates) > 1:
        print(
            f"[freshness-guard] ambiguous header block ({sorted(dates)}) — treating as undated "
            "and KEEPING the path; the guard cannot tell the real header from a quoted example",
            file=sys.stderr,
        )
        return None
    if not dates:
        return None
    try:
        return datetime.strptime(next(iter(dates)), "%Y-%m-%d").date()
    except ValueError:
        return None  # shape-valid but not a calendar date → treat as undated, fail open


def head_text(rel: str, repo: Path | None = None) -> str | None:
    """The committed version of ``rel``, or None when it is new/unreadable (→ fail-open KEEP)."""
    repo = repo or REPO
    try:
        p = subprocess.run(
            ["git", "-C", str(repo), "show", f"HEAD:{rel}"],
            # ⚠️ encoding + errors are LOAD-BEARING, not tidiness. `text=True` alone decodes with the
            # locale codec and RAISES UnicodeDecodeError on one stray byte; the except below then
            # returned None, which is indistinguishable from "new file" → fail-open KEEP with ZERO
            # output. Reproduced 2026-09-02: a single 0xA0 in the COMMITTED copy let a stale doc
            # through — the 2026-08-29 incident reproducing with the fix installed. The worktree side
            # (`is_regression`) already used utf-8-sig/ignore; this side was asymmetric.
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="ignore",
            timeout=30,
        )
    except Exception as exc:  # noqa: BLE001 — fail-open is the contract; SILENCE was the defect
        # A publisher that fails open INVISIBLY is how the incident lasted four days. Keep the
        # fail-open, lose the silence.
        print(
            f"[freshness-guard] {rel}: HEAD lookup failed ({exc!r}) — keeping it", file=sys.stderr
        )
        return None
    return p.stdout if p.returncode == 0 else None


def is_regression(rel: str, repo: Path | None = None) -> tuple[bool, str]:
    """(True, why) only when BOTH sides carry a real date and the worktree's is older than
    HEAD's by MORE than the clock-skew tolerance."""
    repo = repo or REPO
    try:
        work = (repo / rel).read_text(encoding="utf-8-sig", errors="ignore")
    except OSError:
        return False, ""  # unreadable / absent → not our call to block
    committed = head_text(rel, repo)
    if committed is None:
        return False, ""  # new file → nothing to rewind
    w, h = refresh_date(work), refresh_date(committed)
    if w is None or h is None:
        return False, ""  # not a dated generator output → out of scope
    if (h - w).days > _SKEW_DAYS:
        return True, f"worktree says {w.isoformat()}, HEAD already has {h.isoformat()}"
    return False, ""


def main(paths: list[str]) -> int:
    for rel in paths:
        regressed, why = is_regression(rel)
        if regressed:
            print(
                f"[freshness-guard] DROP {rel}: committing it would REVERT the doc ({why}). "
                "The pipeline did not regenerate it this run — re-run the generator, or commit "
                "it deliberately by hand if the older content is genuinely wanted.",
                file=sys.stderr,
            )
            continue
        print(rel)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
