#!/usr/bin/env python3
"""
Regenerate KILO_MODEL_CAPABILITIES.md from kilo_agents.db.

Replaces the entire file — it's 100% dynamic data with no stable prose.
Called after discover_kilo_agents.py or update_kilo_benchmarks.py.

Usage:
    python scripts/kilo-benchmarks/generate_model_capabilities.py
"""

import sqlite3
from collections import defaultdict
from datetime import date
from pathlib import Path

SCRIPT_DIR = Path(__file__).parent
FABRIK_DIR = SCRIPT_DIR.parent.parent
DB_FILE = SCRIPT_DIR / "kilo_agents.db"
OUT_FILE = FABRIK_DIR / "docs" / "reference" / "kilo" / "KILO_MODEL_CAPABILITIES.md"


def format_cost(cost: float) -> str:
    if cost <= 0:
        return "free"
    if cost < 0.01:
        return f"${cost:.4f}"
    if cost < 1:
        return f"${cost:.3f}"
    if cost < 10:
        return f"${cost:.2f}"
    return f"${cost:.1f}"


def caps_icons(row: dict) -> str:
    icons = []
    if row["is_agentic"]:
        icons.append("\U0001f9e0")  # 🧠 reasoning
    if row["has_tools"]:
        icons.append("\U0001f527")  # 🔧 tools
    if row["has_vision"]:
        icons.append("\U0001f5bc\ufe0f")  # 🖼️ vision
    return " ".join(icons) if icons else "—"


def context_str(ctx_k: int) -> str:
    if not ctx_k:
        return "?"
    if ctx_k >= 1000:
        return f"{ctx_k}K"
    return f"{ctx_k}K"


def main():
    db = sqlite3.connect(DB_FILE)
    db.row_factory = sqlite3.Row

    rows = db.execute("""
        SELECT * FROM agents
        WHERE status = 'active'
        ORDER BY provider, input_cost_per_m, id
    """).fetchall()

    total = len(rows)
    providers_map = defaultdict(list)
    for r in rows:
        providers_map[r["provider"].upper()].append(dict(r))

    total_priced = sum(1 for r in rows if r["input_cost_per_m"] > 0)
    total_vision = sum(1 for r in rows if r["has_vision"])
    total_tools = sum(1 for r in rows if r["has_tools"])
    total_agentic = sum(1 for r in rows if r["is_agentic"])
    providers_count = len(providers_map)

    lines = []
    lines.append("# Kilo Model Capabilities Reference")
    lines.append("")
    lines.append(f"**Auto-generated:** {date.today()} from `kilo_agents.db`")
    lines.append(f"**Total Models:** {total} | **Providers:** {providers_count} | **With Pricing:** {total_priced} ({total_priced*100//total}%)")
    lines.append("")
    lines.append("> This file is auto-generated by `scripts/kilo-benchmarks/generate_model_capabilities.py`.")
    lines.append("> Do not edit manually — it will be overwritten on next pipeline run.")
    lines.append("> To refresh: `python3 scripts/kilo-benchmarks/generate_model_capabilities.py`")
    lines.append("")
    lines.append("---")
    lines.append("")

    # Summary
    lines.append("## Capability Summary")
    lines.append("")
    lines.append(f"| Capability | Count | % |")
    lines.append(f"|---|---|---|")
    lines.append(f"| Tool use (🔧) | {total_tools} | {total_tools*100//total}% |")
    lines.append(f"| Agentic/reasoning (🧠) | {total_agentic} | {total_agentic*100//total}% |")
    lines.append(f"| Vision (🖼️) | {total_vision} | {total_vision*100//total}% |")
    lines.append(f"| With pricing | {total_priced} | {total_priced*100//total}% |")
    lines.append("")

    # Pricing tiers
    lines.append("## Pricing Tiers")
    lines.append("")
    lines.append("| Tier | Input $/M | Use Case |")
    lines.append("|---|---|---|")
    lines.append("| **Free** | $0 | Prototyping, learning |")
    lines.append("| **Budget** | < $0.10 | Quick tasks, linting, simple fixes |")
    lines.append("| **Standard** | $0.10 - $1.00 | Daily development, general coding |")
    lines.append("| **Pro** | $1.00 - $5.00 | Production code, complex features |")
    lines.append("| **Premium** | $5.00 - $15.00 | Critical analysis, architecture |")
    lines.append("| **Ultra** | $15.00+ | Research-grade reasoning |")
    lines.append("")

    # Capability legend
    lines.append("## Legend")
    lines.append("")
    lines.append("| Icon | Meaning |")
    lines.append("|---|---|")
    lines.append("| 🧠 | Agentic — multi-step reasoning, self-correction |")
    lines.append("| 🔧 | Tool use — function calling, can execute actions |")
    lines.append("| 🖼️ | Vision — image/screenshot input |")
    lines.append("")
    lines.append("---")
    lines.append("")

    # Models by provider
    lines.append("## Models by Provider")
    lines.append("")

    for provider in sorted(providers_map.keys(), key=lambda p: -len(providers_map[p])):
        models = providers_map[provider]
        lines.append(f"### {provider} ({len(models)} models)")
        lines.append("")
        lines.append("| Model | Input/M | Output/M | Context | Caps | ELO | TBench |")
        lines.append("|---|---|---|---|---|---|---|")

        for m in models:
            model_id = m["id"].split("/", 1)[1] if "/" in m["id"] else m["id"]
            in_cost = format_cost(m["input_cost_per_m"])
            out_cost = format_cost(m["output_cost_per_m"])
            ctx = context_str(m["context_window_k"])
            caps = caps_icons(m)
            elo = str(m["arena_elo"]) if m["arena_elo"] else "—"
            tbench = f"{m['tbench_accuracy']:.1f}" if m["tbench_accuracy"] else "—"
            lines.append(f"| `{model_id}` | {in_cost} | {out_cost} | {ctx} | {caps} | {elo} | {tbench} |")

        lines.append("")

    db.close()

    OUT_FILE.write_text("\n".join(lines))
    print(f"Generated {OUT_FILE} — {total} models, {providers_count} providers")


if __name__ == "__main__":
    main()
