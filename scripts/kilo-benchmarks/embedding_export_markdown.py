#!/usr/bin/env python3
"""
Generate the human-readable markdown reports for the embedding pipeline:

  - docs/reference/kilo/KILO_EMBEDDING_SELECTION_GUIDE.md
        Today's winners per role, with floors + reason.
  - docs/reference/kilo/KILO_EMBEDDING_CAPABILITIES.md
        Full catalog — every row in `embedding_models`, sorted by cost.

Both files are FULLY auto-generated (rewritten on every run). If we later
want a hand-written philosophy section, switch to the marker-based partial
update pattern from `generate_selection_guide_roster.py`.

Runs after `embedding_role_mapper.py` in `wsl_startup_hook.sh`. Reads
`embedding_roles` (live winners) + `embedding_models` (catalog) + the role
configs YAML. No network, no LLM.

Usage:
    python scripts/kilo-benchmarks/embedding_export_markdown.py
"""

from __future__ import annotations

import sqlite3
import sys
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import yaml

SCRIPT_DIR = Path(__file__).parent
FABRIK_ROOT = SCRIPT_DIR.parent.parent
DB_PATH = SCRIPT_DIR / "kilo_agents.db"
CONFIG_PATH = SCRIPT_DIR / "embedding_role_configs.yaml"

DOCS_DIR = FABRIK_ROOT / "docs" / "reference" / "kilo"
SELECTION_GUIDE_PATH = DOCS_DIR / "KILO_EMBEDDING_SELECTION_GUIDE.md"
CAPABILITIES_PATH = DOCS_DIR / "KILO_EMBEDDING_CAPABILITIES.md"


def _utc_today_iso() -> str:
    return datetime.now(UTC).date().isoformat()


def _fmt_cost(cost: float) -> str:
    """Render input cost in $/M tokens. Sentinel pricing → '?' so a
    broken row is visible in the docs instead of silently rendering '$0'."""
    if cost is None or cost < 0:
        return "?"
    if cost == 0:
        return "$0"
    if cost < 0.01:
        return f"${cost:.4f}/M"
    return f"${cost:.2f}/M"


def _fmt_dim(dim: int | None) -> str:
    return f"{dim:,}" if dim else "—"


def _fmt_bool_flag(value: int) -> str:
    return "✓" if value else "—"


def _fmt_tier(tier: int) -> str:
    return {1: "1 (bulk)", 2: "2 (mid)", 3: "3 (frontier)"}.get(tier, str(tier))


# ─── Selection guide ───────────────────────────────────────────────────────


def _render_role_section(role: str, role_cfg: dict[str, Any], rows: list[sqlite3.Row]) -> str:
    floors = []
    if role_cfg.get("min_quality_tier", 1) > 1:
        floors.append(f"`quality_tier ≥ {role_cfg['min_quality_tier']}`")
    if role_cfg.get("min_context_window_k", 1) > 1:
        floors.append(f"`context_window_k ≥ {role_cfg['min_context_window_k']}k`")
    if role_cfg.get("require_multilingual"):
        floors.append("`is_multilingual = true`")
    if role_cfg.get("require_code_tuned"):
        floors.append("`is_code_tuned = true`")
    if not role_cfg.get("allow_free", False):
        floors.append("free-tier excluded")
    if role_cfg.get("stability_required", True):
        floors.append("GA only (no preview / beta / experimental)")

    floor_line = ", ".join(floors) if floors else "(no floors)"

    # YAML block-scalar `notes` can span multiple lines. Collapse all
    # whitespace to single spaces, then take the first sentence as the
    # role's one-line description.
    notes = " ".join((role_cfg.get("notes") or "").split())
    desc = notes.split(". ")[0].rstrip(".") if notes else ""

    lines = [
        f"### {role} — {desc}" if desc else f"### {role}",
        "",
        f"**Slots:** {role_cfg.get('slots', 1)}  ·  **Floors:** {floor_line}",
        "",
    ]

    if not rows:
        lines.append("> ⚠️  No eligible model satisfies these floors today.")
        lines.append("")
        return "\n".join(lines)

    lines.extend(
        [
            "| Priority | Model | Provider | Cost (input/M) | Context | Dimensions | Tier | Multilingual | Code-tuned |",
            "|---|---|---|---|---|---|---|---|---|",
        ]
    )
    for r in rows:
        lines.append(
            "| P{prio} | `{id}` | {provider} | {cost} | {ctx}k | {dim} | {tier} | {ml} | {code} |".format(
                prio=r["priority"],
                id=r["model_id"],
                provider=r["provider"],
                cost=_fmt_cost(r["input_cost_per_m"]),
                ctx=r["context_window_k"],
                dim=_fmt_dim(r["dimensions"]),
                tier=_fmt_tier(r["quality_tier"]),
                ml=_fmt_bool_flag(r["is_multilingual"]),
                code=_fmt_bool_flag(r["is_code_tuned"]),
            )
        )
    lines.append("")
    return "\n".join(lines)


def _render_selection_guide(
    role_configs: dict[str, dict[str, Any]],
    winners_by_role: dict[str, list[sqlite3.Row]],
) -> str:
    today = _utc_today_iso()
    out: list[str] = [
        "# Kilo Embedding Selection Guide",
        "",
        f"**Last Updated:** {today} (UTC)",
        "",
        "*Auto-generated by `scripts/kilo-benchmarks/embedding_export_markdown.py` "
        "from `embedding_roles` + `embedding_role_configs.yaml`. "
        "Manual edits to this file will be overwritten on the next daily run.*",
        "",
        "---",
        "",
        "## Selection Philosophy",
        "",
        "Mirrors the chat-side pipeline: **cheapest model above the floors wins**. ",
        "For embeddings the floors are stricter than for chat because the dominant ",
        "cost is *re-embedding* the corpus on every winner change, not the per-token ",
        "fetch fee. Floors today come from static spec data (multilingual flag, ",
        "context window, dimensions, GA status) plus a cost-proxy `quality_tier` ",
        "until the MIRACL / MTEB benchmark scrapers ship.",
        "",
        "Selection algorithm (see `embedding_selector.select_for_role`):",
        "",
        "1. Apply hard floors from `embedding_role_configs.yaml`.",
        "2. Sort survivors by `input_cost_per_m ASC`, then `quality_tier DESC`, ",
        "   then `context_window_k DESC`, then `id ASC` (deterministic).",
        "3. Take top-N where N = `slots`.",
        "",
        "Today's pinned winners are also persisted in:",
        "",
        "- SQLite: `embedding_roles` table in `kilo_agents.db`",
        "- JSON: `scripts/kilo-benchmarks/embedding_assignments.json`",
        "- JSON: `scripts/kilo_embeddings_final.json` (compact Traycer export)",
        "- History: `embedding_roles_history` (one snapshot per UTC day)",
        "",
        "---",
        "",
        "## Today's Winners",
        "",
    ]

    for role_name, role_cfg in role_configs.items():
        rows = winners_by_role.get(role_name, [])
        out.append(_render_role_section(role_name, role_cfg, rows))

    out.extend(
        [
            "---",
            "",
            "## How to override",
            "",
            "1. Tune `embedding_role_configs.yaml` (raise/lower floors).",
            "2. Re-run `python scripts/kilo-benchmarks/embedding_role_mapper.py`.",
            "3. Re-run `python scripts/kilo-benchmarks/embedding_export_markdown.py` "
            "(or just the daily `wsl_startup_hook.sh`).",
            "",
            "Hard pins (override the algorithm) are not yet supported for embeddings. ",
            "If needed, add an `embedding_role_pins.yaml` similar to the chat side and ",
            "wire it into `embedding_role_mapper`.",
            "",
        ]
    )
    return "\n".join(out)


# ─── Capabilities catalog ──────────────────────────────────────────────────


def _render_capabilities(rows: list[sqlite3.Row]) -> str:
    today = _utc_today_iso()
    out: list[str] = [
        "# Kilo Embedding Model Capabilities",
        "",
        f"**Last Updated:** {today} (UTC)",
        f"**Total models:** {len(rows)}",
        "",
        "*Auto-generated by `scripts/kilo-benchmarks/embedding_export_markdown.py` "
        "from the live `embedding_models` table. Sorted by `input_cost_per_m` "
        "ascending, then by id.*",
        "",
        "---",
        "",
        "## All embedding models",
        "",
        "| Provider | Model | Cost (input/M) | Context | Dimensions | Tier | Multilingual | Code-tuned | GA | Status |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        out.append(
            "| {provider} | `{id}` | {cost} | {ctx}k | {dim} | {tier} | {ml} | {code} | {ga} | {status} |".format(
                provider=r["provider"],
                id=r["id"],
                cost=_fmt_cost(r["input_cost_per_m"]),
                ctx=r["context_window_k"],
                dim=_fmt_dim(r["dimensions"]),
                tier=_fmt_tier(r["quality_tier"]),
                ml=_fmt_bool_flag(r["is_multilingual"]),
                code=_fmt_bool_flag(r["is_code_tuned"]),
                ga=_fmt_bool_flag(r["is_ga"]),
                status=r["status"] if not r["blocked"] else f"blocked: {r['block_reason'] or ''}",
            )
        )
    out.extend(
        [
            "",
            "---",
            "",
            "## Legend",
            "",
            "- **Tier**: cost-proxy quality tier (1=bulk, 2=mid, 3=frontier). Replace ",
            "  with MIRACL/MTEB-derived score once benchmark scrapers ship.",
            "- **Context**: max input tokens, in thousands.",
            "- **Dimensions**: vector dimensionality. Dash means OpenRouter doesn't ",
            "  advertise this — known dimensions can be backfilled into the DB.",
            "- **Multilingual**: auto-derived from id substrings (`multilingual`, ",
            "  `bge-m3`, `qwen3-embedding`, `gemini-embedding`, `mistral-embed`, ",
            "  `nemotron-embed`).",
            "- **Code-tuned**: auto-derived from id (`code`, `codestral`).",
            "- **GA**: 1 if the id has none of the non-GA markers (`:free`, `preview`, ",
            "  `alpha`, `beta`, `experimental`, `-exp-`, `-rc`).",
            "",
        ]
    )
    return "\n".join(out)


# ─── Main ──────────────────────────────────────────────────────────────────


def run(db_path: Path | str = DB_PATH) -> dict[str, Path]:
    """Generate both markdown files. Returns the paths written."""
    role_configs = yaml.safe_load(CONFIG_PATH.read_text())["roles"]

    conn = sqlite3.connect(db_path)
    conn.row_factory = sqlite3.Row
    try:
        winners_rows = conn.execute(
            """
            SELECT r.role, r.priority, r.model_id, r.score_used,
                   m.provider, m.input_cost_per_m, m.context_window_k,
                   m.dimensions, m.quality_tier, m.is_multilingual, m.is_code_tuned
            FROM embedding_roles r
            JOIN embedding_models m ON m.id = r.model_id
            ORDER BY r.role, r.priority
            """
        ).fetchall()
        catalog_rows = conn.execute(
            "SELECT * FROM embedding_models ORDER BY input_cost_per_m ASC, id ASC"
        ).fetchall()
    finally:
        conn.close()

    winners_by_role: dict[str, list[sqlite3.Row]] = {}
    for r in winners_rows:
        winners_by_role.setdefault(r["role"], []).append(r)

    DOCS_DIR.mkdir(parents=True, exist_ok=True)
    SELECTION_GUIDE_PATH.write_text(_render_selection_guide(role_configs, winners_by_role))
    CAPABILITIES_PATH.write_text(_render_capabilities(catalog_rows))

    print(f"[embedding_export_markdown] wrote {SELECTION_GUIDE_PATH}")
    print(f"[embedding_export_markdown] wrote {CAPABILITIES_PATH}")
    return {
        "selection_guide": SELECTION_GUIDE_PATH,
        "capabilities": CAPABILITIES_PATH,
    }


if __name__ == "__main__":
    run()
    sys.exit(0)
