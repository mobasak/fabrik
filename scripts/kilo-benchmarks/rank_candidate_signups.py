#!/usr/bin/env python3
# AFTER-EDIT: docs/reference/kilo/CANDIDATE_SIGNUPS.md
"""Phase E of best-model-suggester — CANDIDATE_SIGNUPS.md ranker.

Union-selects locked-out (reachable_with_existing_keys=0) rows from `agents`
+ `gpu_providers`, ranks by cost (or price for GPU), and emits
docs/reference/kilo/CANDIDATE_SIGNUPS.md with a break-even hint per row
(uses each row's signup_trigger column).
"""

from __future__ import annotations

import datetime as _dt
import sqlite3
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from rank_coding_subagents import _atomic_write, _safe_md_id  # noqa: E402

DB_PATH = Path(__file__).parent / "kilo_agents.db"
OUT_PATH = (
    Path(__file__).parent.parent.parent / "docs" / "reference" / "kilo" / "CANDIDATE_SIGNUPS.md"
)


def _fetch(conn: sqlite3.Connection) -> list[tuple]:
    """Return unified rows: (kind, id, provider, service_type_or_sku, price, signup_trigger)."""
    agents = conn.execute(
        "SELECT 'llm' AS kind, id, provider, service_type, "
        "COALESCE(cheapest_gateway_price, input_cost_per_m) AS price, signup_trigger "
        "FROM agents "
        "WHERE reachable_with_existing_keys=0 AND status='active' "
        "AND signup_trigger IS NOT NULL"
    ).fetchall()
    gpu = conn.execute(
        "SELECT 'gpu' AS kind, id, provider, gpu_sku, usd_per_hour, signup_trigger "
        "FROM gpu_providers "
        "WHERE reachable_with_existing_keys=0 "
        "AND signup_trigger IS NOT NULL"
    ).fetchall()
    return list(agents) + list(gpu)


def _render(rows: list[tuple]) -> str:
    today = _dt.date.today().isoformat()
    lines = [
        f"Last refresh: {today}",
        "",
        "# Candidate Signups — Watch-list vendors not currently reachable",
        "",
        "Auto-generated by `rank_candidate_signups.py` (daily via `daily_refresh.sh`).",
        "Union-selects `reachable_with_existing_keys=0` rows from `agents` and",
        "`gpu_providers` — vendors that would be worth signing up for based on the",
        "seeded price + signup_trigger note. Cross-reference `AI_VENDOR_ACCESS.md`",
        "before acting; some may have moved between refreshes.",
        "",
        "| # | Kind | Model / SKU | Provider | Price (context) | Signup trigger |",
        "|---|---|---|---|---:|---|",
    ]
    # Sort by kind, then price ascending (NULL last).
    rows_sorted = sorted(rows, key=lambda r: (r[0], r[4] if r[4] is not None else 1e18))
    for i, (kind, mid, provider, service_or_sku, price, trigger) in enumerate(rows_sorted[:30], 1):
        price_str = f"${price:.4f}" if price is not None else "—"
        ctx = "M-in" if kind == "llm" else "/hr"
        lines.append(
            f"| {i} | {kind} | `{_safe_md_id(mid)}` | {provider} | {price_str} {ctx} | {trigger or ''} |"
        )
    if not rows_sorted:
        lines.append("| — | _no candidate signups seeded_ | — | — | — | — |")
    return "\n".join(lines) + "\n"


def main() -> int:
    conn = sqlite3.connect(DB_PATH)
    try:
        rows = _fetch(conn)
    finally:
        conn.close()
    _atomic_write(OUT_PATH, _render(rows))
    print(f"wrote {OUT_PATH} ({len(rows)} candidate rows)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
