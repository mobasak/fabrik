#!/usr/bin/env bash
# AFTER-EDIT: docs/workstation/hooks-index.md, tests/test_install_pre_push_hook.py
#
# Installs the hub's PRE-PUSH gate (pre-commit's pre-push stage: push-gate runs check_duplicates.py)
# SERIALIZED, so concurrent shells never break it (W-cd77f476). scripts/wsl_startup_hook.sh runs this
# from every interactive shell. A bare `pre-commit install -t pre-push` writes the hook IN PLACE
# (install_uninstall.py: open(hook_path, 'w')), so two shells starting together read each other's
# half-written file as a foreign hook and moved it to `pre-push.legacy`; from then on every push
# failed "installed in migration mode" (live 2026-10-11; 8 concurrent installs left a legacy in 16
# of 20 trials). The same in-place rewrite leaves an EMPTY hook for a moment, which git runs as a
# pass — so a hook that is already current is left alone, never rewritten.
#
# Under one flock in the shared hooks dir: heal a legacy that is pre-commit's OWN script (its
# `# ID:` line — pre-commit's own is_our_script test, never the "File generated by pre-commit"
# banner a foreign hook's comment can quote) or an EMPTY one (an interrupted install); skip when
# the hook is current; otherwise install. A foreign legacy is kept and reported (exit 3): pre-commit
# then runs the gate in migration mode, and its own notice of that goes to the discarded stdout.
# A bare `pre-commit install` typed by hand takes no lock; whatever it breaks, the next shell heals.
set -euo pipefail

ROOT=/opt/fabrik
BIN="$ROOT/.venv/bin/pre-commit"
# Test seam, honoured ONLY under the explicit sentinel (install_post_commit_hook.sh's pattern).
if [ "${INSTALL_PRE_PUSH_TEST:-}" = "1" ]; then
  ROOT="${INSTALL_PRE_PUSH_ROOT:-$ROOT}"
  BIN="${INSTALL_PRE_PUSH_BIN:-$BIN}"
fi

# No venv, no pre-commit: nothing to install, and nothing to say on every shell start.
[ -x "$BIN" ] || exit 0

if hp="$(git -C "$ROOT" config --get core.hooksPath)"; then
  echo "install_pre_push_hook: core.hooksPath is set ($hp) — git would never run .git/hooks/pre-push; unset it first" >&2
  exit 1
fi

# The SHARED hooks dir: a worktree's install lands where every checkout of the repo reads it.
hooks="$(cd "$ROOT" && cd "$(git rev-parse --git-common-dir)" && pwd)/hooks"
mkdir -p "$hooks"
hook="$hooks/pre-push"
legacy="$hooks/pre-push.legacy"
py="$(dirname "$BIN")/python"

# pre-commit's OWN test of "a script I generated": its `# ID:` line must carry one of pre-commit's
# real template hashes (install_uninstall.is_our_script) — not any 32-hex line a foreign hook might
# hold. No interpreter → not ours (keep it).
ours() { [ -f "$1" ] && "$py" -c 'import sys; from pre_commit.commands.install_uninstall import is_our_script as o; sys.exit(0 if o(sys.argv[1]) else 1)' "$1" 2>/dev/null; }
present() { [ -e "$1" ] || [ -L "$1" ]; }  # a broken symlink counts: -e alone follows it

exec 9>"$hooks/.pre-push-install.lock"
# Held means a sibling shell is installing this very moment; it finishes the job, and the next shell
# re-checks for free. Waiting would only block a prompt behind a hung holder.
flock -n 9 || exit 0

# Heal: pre-commit can never run a legacy it generated itself; an empty file or a dangling symlink
# is debris from an interrupted install.
if { [ -L "$legacy" ] && [ ! -e "$legacy" ]; } || { [ -f "$legacy" ] && { [ ! -s "$legacy" ] || ours "$legacy"; }; }; then
  rm -f "$legacy"
fi

# Current: ours, executable (git silently SKIPS a hook without +x), for this interpreter (compared by
# real path, so a symlinked .venv reads as the same one) and the pre-push stage. Rewriting a current
# hook would only open the empty-hook window.
installed_py="$( { sed -n 's/^INSTALL_PYTHON=//p' "$hook" 2>/dev/null || true; } | head -1)"  # no hook yet → empty
if ! present "$legacy" && [ -x "$hook" ] && ours "$hook" \
  && [ -n "$installed_py" ] && [ "$(realpath -m "$installed_py")" = "$(realpath -m "$py")" ] \
  && grep -qF -- "--hook-type=pre-push" "$hook"; then
  exit 0
fi

# 9>&-: the child must not inherit the lock, or anything it left running would hold it.
if ! (cd "$ROOT" && "$BIN" install -t pre-push >/dev/null 9>&-); then
  echo "install_pre_push_hook: pre-commit install -t pre-push failed in $ROOT" >&2
  present "$legacy" && echo "install_pre_push_hook: and a $legacy is left behind" >&2
  exit 1
fi

if present "$legacy"; then
  echo "install_pre_push_hook: the push gate runs in migration mode with a foreign $legacy — move it aside if it is not wanted" >&2
  exit 3
fi
