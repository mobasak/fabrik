#!/usr/bin/env python3
# AFTER-EDIT: tests/test_review_receipt.py, tests/test_task_lane_receipt.py, scripts/task_lane.py (check_review_receipt reads the Command and Surface lines), commands/_sources/fabrik-review.md, commands/_sources/fabrik-execute-plan.md, scripts/enforcement/check_review_coverage.py, scripts/fabrik_synced_manifest.py | none
"""Review-artifact skeleton — `--init` emits the grammar `check_review_coverage.py` grades.

Why a generator: the artifact's mechanical half (the pasted rubric header, the `Surface:` hash
line, the standing recurrence rows, the ledger and phase-verdict shapes) was hand-written per
review and mis-shaped often enough to fail its own gate (two grammar-gate failures and seven
hand-built receipts in one plan, 2026-09-06). The generator writes that half; the reviewer
writes the verdicts. It never pre-fills a verdict, a ledger row or a gate result: the file is
born `Status: IN-PROGRESS` (exempt from the gate until the reviewer flips it), and every slot
that would satisfy the gate if left alone is spelled `UNCHECKED` — a lazy flip fails loudly.

    python scripts/review_receipt.py --init --changed <paths…> [--out <file> | --scope <slug>]
                                     [--title <h1>] [--plan <path>] [--range A..B]
                                     [--project-root <repo>]
                                     [--command /fabrik-review|/fabrik-review-scoped] [--lane]

`--command` names the review on the `**Command:**` line (default `/fabrik-review`; only the two
review-family commands are accepted). `--lane` adds the exact line `**Lane:** fabrik-task`: the
receipt is a `/fabrik-task` phase-4 review, the marker the in-lane scope-growth stop keys on
(spec 2026-10-02 D8; `check_review_coverage.py` gains that reader in plan T04). A `/fabrik-task` close that owes a FULL review
(`task_lane.check_review_receipt`, check (c)) accepts only `/fabrik-review`.

The `Surface:` anchor covers the tracked diff (`git diff HEAD` or `--range`) PLUS the content
of every UNTRACKED changed path — a review's changed set is routinely new files, which `git
diff` never shows; without them the anchor was md5("") on exactly the mandated `--init` moment.

Exit codes: 0 written · 1 the rubric could not run, or the surface is EMPTY (fail closed — an
un-armed artifact, or one anchored to nothing, is the un-reviewed review the gate exists to
refuse) · 2 the target already exists (exclusive create; never overwrite a review in flight).
Fleet-synced (`fabrik_synced_manifest.py`): the commands that call it render box-wide.
"""

from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import os
import re
import shlex
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REVIEWS_DIR = Path("docs/development/reviews")
COMMANDS = ("/fabrik-review", "/fabrik-review-scoped")
LANE_LINE = "**Lane:** fabrik-task"
_DATED = re.compile(r"^\d{4}-\d{2}-\d{2}-")
# One law, both writers: the gate's own predicate for "a rubric was RUN" — imported from the
# synced gate when it is beside us (every synced repo carries scripts/enforcement/), the literal
# twin otherwise; `tests/test_review_receipt.py` pins the two patterns equal so they cannot drift.
_RUBRIC_RUN_LITERAL = re.compile(r"REVIEW RUBRIC\b[^\n]*generated by review_rubric\.py")
try:
    sys.path.insert(0, str(HERE.parent))
    from scripts.enforcement.check_review_coverage import RUBRIC_RUN  # type: ignore[no-redef]
except Exception:  # noqa: BLE001 — a project without the gate module still gets the literal
    RUBRIC_RUN = _RUBRIC_RUN_LITERAL

# One row per standing recurrence class — the labels carry the exact words
# check_review_coverage.RECURRENCE matches (fail-open · cost/quota/limit · boundary/sentinel/prefix
# · behavior-without-a-test); the two trailing rows are the contract's own classes.
STANDING_ROWS = (
    "Recurrence: fail-open/fail-closed — a swallowed error or an absent check that reads as success",
    "Recurrence: cost/quota accounting — pool units scored, native seats counted, a limit at its edges",
    "Recurrence: boundary/sentinel/prefix — an off-by-one, a sentinel value, a prefix-vs-exact match",
    "Recurrence: behavior-without-a-test — a contract row no test kills (mutation asserted)",
    "Recurrence: denominator on every count — bounded searches state their bound",
    "Recurrence: proxy-as-evidence — the real check EXECUTED, not read",
)


def _git(root: Path, *args: str) -> tuple[int, str]:
    r = subprocess.run(["git", *args], cwd=root, capture_output=True, text=True, check=False)
    return r.returncode, r.stdout


def _git_bytes(root: Path, *args: str) -> tuple[int, bytes]:
    """Raw stdout — the diff is hashed byte-exact (a text decode with `replace` would hash a
    lossy rendering of a binary hunk)."""
    r = subprocess.run(["git", *args], cwd=root, capture_output=True, check=False)
    return r.returncode, r.stdout


def _surface(root: Path, changed: list[str], rng: str | None) -> tuple[str, int]:
    """The anchor line and the byte count it hashes (0 = nothing differs — the caller refuses)."""
    _, head = _git(root, "rev-parse", "HEAD")
    head = head.strip() or "no-git-HEAD"
    if rng is not None:
        # exactly `<a>..<b>`: a three-dot range would make the tip `.B`, an open end or a bare
        # rev names no tip, and the receipt's `Surface:` line must end at a real commit.
        parts = rng.split("..")
        if len(parts) != 2 or not all(p and p[0] != "." and p[-1] != "." for p in parts):
            sys.stderr.write(f"review_receipt: --range {rng!r} is not exactly `<a>..<b>`\n")
            raise SystemExit(2)
        # the range's own endpoint, resolved — HEAD alone misdescribes a `A..B` surface
        rc, tip = _git(root, "rev-parse", "--verify", "-q", f"{parts[1]}^{{commit}}")
        if rc != 0 or not tip.strip():
            sys.stderr.write(
                f"review_receipt: --range tip `{parts[1]}` does not resolve to a commit\n"
            )
            raise SystemExit(2)
        head = f"{head}; range tip {tip.strip()}"
    diff_cmd = ["diff", rng, "--", *changed] if rng else ["diff", "HEAD", "--", *changed]
    rc, blob = _git_bytes(root, *diff_cmd)
    if rc != 0:
        sys.stderr.write(f"review_receipt: `git {' '.join(diff_cmd)}` failed (rc={rc})\n")
        raise SystemExit(1)
    _, untracked_out = _git(root, "ls-files", "--others", "--exclude-standard", "--", *changed)
    untracked = [p for p in untracked_out.splitlines() if p.strip()]
    for p in untracked:
        fp = root / p
        if fp.is_file():
            blob += f"\n--- untracked: {p}\n".encode() + fp.read_bytes()
    digest = hashlib.md5(blob, usedforsecurity=False).hexdigest()  # a cross-run anchor
    # shell-quoted: a path holding a space must survive the round trip `task_lane` and --restamp make
    # (`shlex.split`); a plain path is written exactly as before (W-ebbedc88 review A-S3)
    shown = f"git diff {rng or 'HEAD'} -- {shlex.join(changed)}"
    extra = f" + {len(untracked)} untracked file(s)" if untracked else ""
    line = f"`git rev-parse HEAD` = {head}; `{shown}`{extra} md5 {digest} ({len(blob)} bytes)"
    return line, len(blob)


# The working-tree form `_surface` writes when no --range is given. `task_lane.check_review_receipt`
# parses the same line (its `_WT_SURFACE`); tests/test_task_lane_receipt.py round-trips a real
# `--init` through it, so a change to `_surface`'s wording reds there.
_WT_SURFACE = re.compile(
    r"`git rev-parse HEAD` = (?P<head>\S+); `git diff HEAD -- (?P<paths>[^`]*)`"
    r"(?: \+ (?P<n>\d+) untracked file\(s\))? md5 (?P<md5>[0-9a-f]{32}) \((?P<bytes>\d+) bytes\)"
)
_SURFACE_LINE = re.compile(r"^\*\*Surface:\*\* ([^\r\n]*)", re.M)


# What a receipt whose surface is already COMMITTED needs (kaizen 01M4V0B03B row 1791907300): nothing,
# when the commit holds the reviewed bytes — task_lane's check (d) rebuilds them from base..last — or a
# new receipt. A `--restamp --range` would downgrade a byte-checked receipt to a tip-only one.
_COMMITTED_REMEDY = (
    "Already committed? A working-tree receipt already passes task_lane's check (d) when the commit "
    "holds the reviewed bytes; if it does not, re-make the receipt with `--init --range <base>..<last>`"
)


def restamp(root: Path, receipt: Path) -> int:
    """Re-anchor an existing receipt's working-tree **Surface:** line to the tree as it is NOW.

    `--init` hashes the tree when the review STARTS; every fix the review makes then changes the
    diff, so the receipt no longer matches its commit and a `/fabrik-task` close refuses it
    (`task_lane.check_review_receipt` check (d)). Run this after the last fix and before the
    commit: it rewrites only that one line, over the paths the line already names (W-ebbedc88).

    THE CHEAPEST WAY TO SATISFY IT WITHOUT THE OUTCOME (D-253): restamp a tree that still holds
    unreviewed edits — the line then matches a commit nobody reviewed. That costs exactly what
    hand-editing the line or forging a `--range` tip costs today; the review's own closing pass
    over the pinned surface is the counter-measure, not this verb.
    """
    try:
        # newline="" keeps the file's own line endings: a restamp rewrites one line, nothing else
        with receipt.open(encoding="utf-8", newline="") as fh:
            text = fh.read()
    except OSError as exc:
        sys.stderr.write(f"review_receipt: --restamp {receipt}: unreadable ({exc})\n")
        return 1
    lines = _SURFACE_LINE.findall(text)
    if len(lines) != 1:
        sys.stderr.write(
            f"review_receipt: --restamp {receipt}: {len(lines)} **Surface:** line(s), not exactly one\n"
        )
        return 1
    m = _WT_SURFACE.fullmatch(lines[0].strip())
    if m is None:
        sys.stderr.write(
            f"review_receipt: --restamp {receipt}: the **Surface:** line is not the working-tree "
            "form `--init` writes without --range (a range receipt is re-made with --range)\n"
        )
        return 1
    try:
        paths = shlex.split(m.group("paths"))
    except ValueError as exc:
        sys.stderr.write(f"review_receipt: --restamp {receipt}: unparseable paths ({exc})\n")
        return 1
    surface, nbytes = _surface(root, paths, None)
    if nbytes == 0:
        sys.stderr.write(
            f"review_receipt: --restamp {receipt}: the surface is EMPTY — nothing differs from "
            f"HEAD on its paths and none is untracked. {_COMMITTED_REMEDY}\n"
        )
        return 1
    new = _SURFACE_LINE.sub(lambda _m: f"**Surface:** {surface}", text, count=1)
    tmp = receipt.with_name(receipt.name + ".restamp.tmp")
    with tmp.open("w", encoding="utf-8", newline="") as fh:
        fh.write(new)
    os.replace(tmp, receipt)
    print(f"restamped {receipt}: {surface}")
    return 0


def _rubric(root: Path, changed: list[str]) -> str:
    """The hub's extractor, run against `root` — a project root need not carry the script."""
    r = subprocess.run(
        [
            sys.executable,
            str(HERE / "review_rubric.py"),
            "--changed",
            *changed,
            "--project-root",
            str(root),
        ],
        cwd=root,
        capture_output=True,
        text=True,
        check=False,
    )
    if r.returncode != 0 or not RUBRIC_RUN.search(r.stdout):
        sys.stderr.write(
            "review_receipt: review_rubric.py did not produce a rubric the gate recognizes — "
            f"refusing to write an un-armed artifact (rc={r.returncode}): {r.stderr.strip()[:400]}\n"
        )
        raise SystemExit(1)
    return r.stdout.rstrip("\n")


def render(
    *,
    title: str,
    changed: list[str],
    surface: str,
    rubric: str,
    plan: str | None,
    command: str = COMMANDS[0],
    lane: bool = False,
) -> str:
    cmd = f"$ python scripts/review_rubric.py --changed {' '.join(changed)}"
    hunt_rows = "\n".join(
        f"| Hunt: `{p}` — every changed hunk, its enclosing function, its callers | UNCHECKED |"
        for p in changed
    )
    standing = "\n".join(f"| {row} | UNCHECKED |" for row in STANDING_ROWS)
    plan_line = f"**Plan:** `{plan}`\n" if plan else ""
    lane_line = f"{LANE_LINE}\n" if lane else ""
    return f"""# {title}

**Status:** IN-PROGRESS
**Surface:** {surface}
**Command:** {command} · **Changed:** {", ".join(f"`{p}`" for p in changed)}
{lane_line}{plan_line}
## Coverage Checklist

Rubric invocation (verbatim output — the gate reads the generated header, never a prose mention):

```text
{cmd}
{rubric}
```

| Class | Status |
|---|---|
{hunt_rows}
{standing}

Verdict grammar (the gate refuses anything else): `CLEAN (<the paths/lines hunted>)` — a CLEAN row
must name a path and run past 70 characters · `FIXED r<n> (<what changed>)` · `REFUTED (<the
disproving line>)` · `RECORDED — unexecuted (<why>)` · `RECORDED — measured (<why>)` ·
`RECORDED — hygiene false positive (<why>)` · `RECORDED — by design`, whose parentheses hold owner ids
only — each the owning row's first-cell id and the EARLIER round that adjudicated it, or a `D-nnn`
row of this checkout's ledger with no round, `;`-joined — with its reason AFTER the closing
parenthesis and an em dash (the § Residual block below shows the shape). Every OTHER RECORDED reason
is PARENTHESISED, never colon-delimited (a colon would spell the `unexecuted: N` counter the ledger
refuses). `UNCHECKED`
may survive only under a `## BLOCKED` escalation (a finding + 3 failed attempts).

## Pass Ledger

ONE table, one row per pass, counts punctuated (`found: F, new: N, confirmed: C, fixed: X,
unexecuted: U`) — the gate reads the LAST row as the exit round and refuses a second ledger group.
`found:` counts raw candidates, `new:` is prose the graders do not parse, `confirmed:` counts the
candidates EXECUTED and reproduced (the exit counter — a round is quiet at `confirmed: 0` and
`fixed: 0` with `unexecuted:` 0 or absent), `unexecuted:` counts code candidates RECORDED
unexecuted. Minimum two passes; the fixing pass is never the last; the closing pass re-derives
every count and anchor and says so in its Method cell, and its Finders cell names the seats that
read it by model token (`opus×1`, `sonnet×2`) — a round the orchestrator alone read cannot close.

| Pass | Finders | Counters | Method |
|---|---|---|---|

Row shapes (quoted here, so the gate does not read them as passes):

```text
| Pass 1 | native opus×1 + sonnet×2 | found: N, new: N, confirmed: C, fixed: X, unexecuted: U | method: citation |
| Pass 2 | native opus×1 + sonnet×2 | found: 0, new: 0, confirmed: 0, fixed: 0, unexecuted: 0 | method: re-derivation |
```

## Residual

Every candidate that did not enter `confirmed:` is recorded here, one row each, in the verdict
grammar of `/fabrik-review` § Phase 2 (the fenced block under the next heading is an EXAMPLE, never rows).

### Verdict grammar — an EXAMPLE, never rows

(quoted so no reader — human or scan — takes this template's own sample rows for the receipt's residuals):

```text
| F12 | RECORDED — unexecuted (3 probe attempts timed out) |
| F19 | RECORDED — by design (F4, round 3; D-203) — <why> |
| F31 | RECORDED — measured (a prevalence figure; makes no code or doc claim) |
```

`RECORDED — by design` names the OWNING row's first-cell id and the EARLIER round that adjudicated
it (or a `D-nnn` with no round); each `;`-part of a by-design parenthetical is an owner, never a
reason — the reason follows the closing parenthesis. What the gate refuses in a by-design verdict is the
message list of `check_review_coverage.py::_residual_errors`, read there and never restated here;
whether a `D-nnn` is a row of the ledger is checked only where `_ledger_ids` reads a `docs/DECISIONS.md`
with rows, and is not checked otherwise. `RECORDED — measured` and `RECORDED — unexecuted` never enter
`confirmed:`; `unexecuted:` on the closing row is what keeps an unexecuted CODE candidate from closing the loop.

## Per-phase verdicts

### Phase 1 — <title>: UNCHECKED

## Gate

`final_gate.py --check --json`, pasted verbatim (check_convergence reads the fenced
`"status": "success"`). Close order per `/fabrik-review` § Reporting: run it while this receipt reads
`Status: IN-PROGRESS`, paste it here, flip to CONVERGED, re-run and paste that run in place of the first:

```json
UNCHECKED — the IN-PROGRESS gate run goes here first, then the post-flip run replaces it
```

A red caused only by another lane's work is pasted as is, with ONE line beside it (`/fabrik-review` § Reporting):
`GATE-SCOPE: out-of-surface — <failing check>; findings naming this surface: 0 of <N>; measured by: <command>`,
`<N>` the failing check's total findings (at least 1).
"""


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description="Emit a review-artifact skeleton (--init), or re-anchor one (--restamp)."
    )
    verb = ap.add_mutually_exclusive_group(required=True)
    verb.add_argument("--init", action="store_true")
    verb.add_argument(
        "--restamp",
        type=Path,
        metavar="RECEIPT",
        help="rewrite an existing receipt's working-tree **Surface:** line to the tree as it is "
        "now — after the review's last fix, before the commit",
    )
    ap.add_argument("--changed", nargs="+", help="changed repo-relative paths (--init)")
    ap.add_argument(
        "--out", type=Path, help="artifact path (default: reviews/<date>-<scope>-review.md)"
    )
    ap.add_argument("--scope", help="artifact stem slug when --out is not given")
    ap.add_argument("--title", help="H1 (default derived from the scope)")
    ap.add_argument("--plan", help="the plan path this review receipts, if any")
    ap.add_argument(
        "--range", dest="rng", help="A..B diff range for the Surface hash (default HEAD)"
    )
    ap.add_argument("--project-root", type=Path, default=Path.cwd())
    ap.add_argument(
        "--command",
        choices=COMMANDS,
        default=COMMANDS[0],
        help="the review command on the **Command:** line (default /fabrik-review)",
    )
    ap.add_argument(
        "--lane",
        action="store_true",
        help=f"write `{LANE_LINE}` — a /fabrik-task phase-4 review",
    )
    a = ap.parse_args(argv)
    root = a.project_root.resolve()
    if a.restamp is not None:
        if a.rng is not None:
            sys.stderr.write(
                "review_receipt: --restamp does not take --range — a restamp re-anchors the "
                f"working-tree form only. {_COMMITTED_REMEDY}\n"
            )
            return 2
        target = a.restamp if a.restamp.is_absolute() else root / a.restamp
        return restamp(root, target)
    if not a.changed:
        ap.error("--init needs --changed")
    if a.out is None:
        if not a.scope:
            ap.error("--out or --scope is required")
        # a plan STEM already starts with its date — never double it
        stem = a.scope if _DATED.match(a.scope) else f"{dt.date.today():%Y-%m-%d}-{a.scope}"
        a.out = root / REVIEWS_DIR / f"{stem}-review.md"
    out = a.out if a.out.is_absolute() else root / a.out
    if out.exists():
        sys.stderr.write(
            f"review_receipt: {out} exists — refusing to overwrite a review in flight\n"
        )
        return 2
    surface, nbytes = _surface(root, a.changed, a.rng)
    if nbytes == 0:
        sys.stderr.write(
            "review_receipt: the surface is EMPTY — nothing differs from "
            f"{a.rng or 'HEAD'} on the changed paths and none is untracked. A review anchored "
            "to nothing reviews nothing: pass --range <base>..HEAD for committed work, or check "
            "the paths.\n"
        )
        return 1
    rubric = _rubric(root, a.changed)
    title = a.title or f"Review — {a.scope or out.stem.removesuffix('-review')}"
    text = render(
        title=title,
        changed=a.changed,
        surface=surface,
        rubric=rubric,
        plan=a.plan,
        command=a.command,
        lane=a.lane,
    )
    out.parent.mkdir(parents=True, exist_ok=True)
    try:
        with out.open("x", encoding="utf-8") as fh:  # exclusive: three sessions share this tree
            fh.write(text)
    except FileExistsError:
        sys.stderr.write(f"review_receipt: {out} appeared meanwhile — refusing to overwrite\n")
        return 2
    print(f"wrote {out} ({len(text)} bytes) — Status: IN-PROGRESS; fill every UNCHECKED, then flip")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
