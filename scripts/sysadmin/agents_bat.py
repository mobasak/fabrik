#!/usr/bin/env python3
# AFTER-EDIT: docs/reference/repo-coordinator-rollout.md | tests/test_agents_bat.py
"""agents_bat.py [--opt DIR] [--desktop DIR] [--distro NAME] [--replace FILE]... — one "<Repo> Agents.bat" per repo.

For every repo directly under --opt (default /opt) that registers its agents in .fabrik/session-agents.json, it makes
the desktop launcher the operator double-clicks to open that repo's agents_up.sh tmux grid (W-bb6c9d9a, D-1042). By
default it only prints each target and its text; it writes only under an explicit --desktop, the operator-named
location, because the desktop is outside every repo.

Each .bat is self-contained — no hand-made Windows Terminal profile. wt.exe has no font-size option, so the .bat
writes a WT JSON fragment (%LOCALAPPDATA%\\Microsoft\\Windows Terminal\\Fragments\\Fabrik\\<repo>.json) defining a
profile "<Repo> Agents" at font size 9 — written to a temp file by one redirect-first block, then moved into place, so
WT never reads half of it. settings.json is never written by us; WT itself adds a `"source": "Fabrik"` stub there for a
fragment profile. Then `start "" wt.exe -M -w new new-tab -p ... wsl.exe --distribution <distro> --exec bash -l
<agents_up.sh> /opt/<repo>` — every argument after wsl.exe free of spaces, `;` and `--`, so wt's argv handling cannot
change it, and explicit, so the grid opens even before WT has loaded the fragment (at the default font then).

An existing target is rewritten only when this script wrote it (its marker line), left alone when identical, and
otherwise refused unless named by --replace; a refusal leaves the file untouched and the other targets are still
written (exit 2). Repo and distro names reach cmd, JSON and bash text, so both must match [A-Za-z0-9][A-Za-z0-9._-]*,
and two repos whose names differ only by case are refused, since the desktop ignores case.

COBRA (D-253): the cheapest way to pass the tests is a .bat whose TEXT is right and that never opens a grid — no
Windows runner exists here. The counter is the runbook's acceptance check on the operator's machine (the grid opens
at 9pt with no banner or dialog), named there as the live proof.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path

AGENTS_UP = "/opt/fabrik/scripts/sysadmin/agents_up.sh"
MARKER = "rem generated by /opt/fabrik/scripts/sysadmin/agents_bat.py"
FONT_SIZE = 9
_NAME = re.compile(r"[A-Za-z0-9][A-Za-z0-9._-]*")


def bat_name(repo: str) -> str:
    return f"{repo[:1].upper()}{repo[1:]} Agents.bat"


def bat_text(repo: str, distro: str) -> str:
    title = f"{repo[:1].upper()}{repo[1:]} Agents"
    command = f"wsl.exe --distribution {distro} --exec bash -l {AGENTS_UP} /opt/{repo}"
    fragment = json.dumps(
        {
            "profiles": [
                {
                    "name": title,
                    "commandline": command,
                    "tabTitle": title,
                    "suppressApplicationTitle": True,
                    "font": {"size": FONT_SIZE},
                    "hidden": False,
                }
            ]
        },
        indent=2,
    ).splitlines()
    lines = [
        "@echo off",
        MARKER,
        f"rem from /opt/{repo}/.fabrik/session-agents.json - re-run it, never hand-edit this file.",
        f"rem {title} - the builders side by side in one tmux grid in WSL, each resuming its own session in its",
        "rem own worktree. The coordinator runs in VS Code. The font comes from a Windows Terminal fragment this file",
        "rem writes; it applies once Windows Terminal has restarted after the first run.",
        'set "FRAG=%LOCALAPPDATA%\\Microsoft\\Windows Terminal\\Fragments\\Fabrik"',
        'if not exist "%FRAG%\\" mkdir "%FRAG%"',
        f'> "%FRAG%\\{repo}.json.tmp" (',
        *(f"  echo {ln}" for ln in fragment),
        ")",
        f'move /y "%FRAG%\\{repo}.json.tmp" "%FRAG%\\{repo}.json" >nul',
        f'start "" wt.exe -M -w new new-tab -p "{title}" --title "{title}" --suppressApplicationTitle {command}',
    ]
    return "\r\n".join(lines) + "\r\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n", 1)[0])
    ap.add_argument(
        "--opt", default="/opt", help="the folder whose repos are scanned (default: /opt)"
    )
    ap.add_argument("--desktop", help="write the .bat files here; without it nothing is written")
    ap.add_argument(
        "--distro",
        default=os.environ.get("WSL_DISTRO_NAME", ""),
        help="the WSL distro the .bat starts",
    )
    ap.add_argument(
        "--replace",
        action="append",
        default=[],
        help="a desktop file name this script may overwrite once",
    )
    args = ap.parse_args(argv)

    if not _NAME.fullmatch(args.distro or ""):
        print(
            f"agents_bat: distro {args.distro!r} is not a WSL distro name ([A-Za-z0-9][A-Za-z0-9._-]*)",
            file=sys.stderr,
        )
        return 2
    desk = Path(args.desktop) if args.desktop else None
    if desk is not None and not desk.is_dir():
        print(f"agents_bat: --desktop {desk} is not a folder; nothing written", file=sys.stderr)
        return 2

    repos = sorted(
        p.parent.parent.name for p in Path(args.opt).glob("*/.fabrik/session-agents.json")
    )
    by_case: dict[str, list[str]] = {}
    for repo in repos:
        by_case.setdefault(bat_name(repo).lower(), []).append(repo)
    clash = [names for names in by_case.values() if len(names) > 1]
    if clash:
        print(
            f"agents_bat: these repos share one desktop file name: {clash}; nothing written",
            file=sys.stderr,
        )
        return 2

    rc = 0
    for repo in repos:
        if not _NAME.fullmatch(repo):
            print(f"agents_bat: repo folder {repo!r} is not a safe name; skipped", file=sys.stderr)
            rc = 2
            continue
        name, text = bat_name(repo), bat_text(repo, args.distro)
        if desk is None:
            print(f"== {name}\n{text.replace(chr(13), '')}")
            continue
        target = desk / name
        if target.exists():
            old = target.read_bytes()
            if old == text.encode("ascii"):
                print(f"agents_bat: {target} is current")
                continue
            if MARKER.encode("ascii") not in old and name not in args.replace:
                print(
                    f"agents_bat: {target} exists and was not written by this script; left untouched "
                    f'(--replace "{name}" overwrites it)',
                    file=sys.stderr,
                )
                rc = 2
                continue
        target.write_bytes(text.encode("ascii"))
        print(f"agents_bat: wrote {target}")
    return rc


if __name__ == "__main__":
    sys.exit(main())
