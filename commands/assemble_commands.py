def _sections(lines):
    idx = [i for i, line in enumerate(lines) if re.match(r"^#{2,3} ", line)] + [len(lines)]
    # Deliberately ragged: `idx[1:]` is one shorter than `idx` — the pairing IS
    # (start, next_start), so the sequences must NOT be the same length.
    return list(zip(idx, idx[1:], strict=False))


def extract():
    SRC.mkdir(exist_ok=True)
    for f in sorted(BACKUP.glob("*.md")):
        name = f.stem
        lines = f.read_text().split("\n")
        plan = EXTRACT.get(name, [])
        out, done = [], set()
        secs = _sections(lines)
        repl = {}
        for block, frag, after in plan:
            pat = BLOCK_PATTERNS[block]
            first_only = block.endswith("_first")
            for a, b in secs:
                if pat.match(lines[a]) and a not in repl:
                    if first_only and block in done:
                        continue
                    if not first_only and lines[a].startswith("### "):
                        continue
                    repl[a] = (b, frag, after)
                    done.add(block)
                    break
        i = 0
        while i < len(lines):
            if i in repl:
                b, frag, after = repl[i]
                out.append("{{include:" + frag + "}}")
                if after:
                    out.append(after.strip("\n"))
                    out.append("")
                i = b
            else:
                out.append(lines[i])
                i += 1
        (SRC / f.name).write_text("\n".join(out))
    print(f"extracted {len(list(SRC.glob('*.md')))} sources from {BACKUP}")


def _description_of(text: str) -> str:
    """Pull the `description:` scalar from a rendered command's frontmatter."""
    m = re.search(r"^description:\s*(.+)$", text, flags=re.M)
    return m.group(1).strip() if m else ""


def _requote_command_description(text: str) -> str:
    """Rewrite a rendered command's frontmatter `description:` scalar as a YAML
    double-quoted scalar — the same `_yaml_dq` escaping `_emit_skill` already
    applies to the skill wrapper — but ONLY when the plain (unquoted) scalar
    doesn't actually parse. A hand-authored plain scalar containing a bare
    `: ` (e.g. "Stage: utility", "found: 0", `TRIGGER — EN: "..."`) is invalid
    YAML (ScannerError on `yaml.safe_load`) even though some renderers
    silently tolerate it; quoting fixes that defect class. Gating on a real
    `yaml.safe_load` probe (not a hand-rolled `": "` heuristic) keeps every
    description that was already valid byte-identical — only the previously-
    broken ones change. Only the `description:` line is touched — other
    frontmatter keys pass through untouched.

    A syntax-only `safe_load` probe isn't enough: several plain scalars PARSE
    without error but silently change MEANING, not just spelling — a ` #` mid-line
    starts a YAML comment and truncates the string (`... #1 priority ...`), a
    leading `&name` is consumed as an anchor label instead of literal text
    (`&anchor thing`), an ISO-shaped value resolves to a `date` object instead of
    a string (`2026-08-07`), and `yes`/`no`/`on`/`off` resolve to `bool` under
    PyYAML's default (YAML 1.1) resolver. All four still parse "successfully" —
    the only way to catch them is to parse THEN compare the round-tripped value
    back to the original string, not just catch exceptions."""
    if not text.startswith("---"):
        return text
    end = text.index("\n---", 3)
    fm = text[3:end]

    def repl(m: re.Match) -> str:
        val = m.group(1).strip()
        if len(val) >= 2 and val.startswith('"') and val.endswith('"'):
            return f"description: {val}"  # already a quoted scalar — leave it alone
        try:
            parsed = yaml.safe_load(f"description: {val}")
            parsed_val = parsed.get("description") if isinstance(parsed, dict) else None
            if isinstance(parsed_val, str) and parsed_val == val:
                return f"description: {val}"  # already a valid plain scalar — untouched, byte-equal round-trip
            return (
                f'description: "{_yaml_dq(val)}"'  # parsed to a non-string, or a lossy round-trip
            )
        except yaml.YAMLError:
            return f'description: "{_yaml_dq(val)}"'

    fm2 = re.sub(r"^description:\s*(.+)$", repl, fm, count=1, flags=re.M)
    return "---" + fm2 + text[end:]


def _agent_frontmatter_defect(text: str) -> str | None:
    """Why Claude Code would refuse to REGISTER this agent, or None.

    Measured 2026-09-08: `fabrik-reviewer` — the authoritative review seat every /fabrik-review is
    contractually required to dispatch — was absent from the agent roster for weeks. Its source had
    grown a second PARAGRAPH inside the `description:` scalar, and a blank line at column 0 ends a
    plain YAML scalar: the loader dropped the whole definition, silently, while `agent_drift` stayed
    green (the file renders fine; it just does not LOAD). The dispatcher only learns of it when a
    Task call answers "agent type not found" — mid-review, one seat short.
    """
    if not text.startswith("---"):
        return "no YAML frontmatter block"
    try:
        block = text[3 : text.index("\n---", 3)]
    except ValueError:
        return "unterminated frontmatter block"
    if "\n\n" in block:
        return "blank line inside the frontmatter — it ends the scalar and unregisters the agent"
    if not re.search(r"^name: \S", block.lstrip("\n"), re.M):
        return "no `name:` key"
    return None


def _render_agent(src: Path, frags: dict[str, str]) -> str:
    """One agent definition, banner-stamped and carrying the machinery-findings duty.

    The frontmatter is NEVER touched beyond the banner insert: Claude Code parses `name:` /
    `description:` / the tool fields out of it, so a renderer that disturbed the block would
    silently unregister the agent rather than fail loudly.
    """
    text = src.read_text()
    defect = _agent_frontmatter_defect(text)
    if defect:
        raise SystemExit(f"agents/{src.name}: {defect} — fix the SOURCE, then re-render")
    body = frags.get(_AGENT_FEEDBACK, "")
    if body and body.split("\n", 1)[0] not in text:
        text = text.rstrip("\n") + "\n\n" + body + "\n"
    if text.startswith("---"):
        end = text.index("\n---", 3) + 4
        return text[:end] + "\n" + BANNER + text[end:].lstrip("\n")
    return BANNER + text


def agent_drift(dest: Path) -> list[str]:
    """Installed agent definitions vs a fresh render — the check that makes the repo CANONICAL.

    Before this existed, `~/.claude/agents/` was hand-authored and box-local: no source to diff, so a
    defect in a subagent's brief could not be reviewed and the corpus check had no jurisdiction over
    the agents its commands dispatch.
    """
    frags = {p.stem: p.read_text().rstrip("\n") for p in FRAG.glob("*.md")}
    drift: list[str] = []
    for src in sorted(AGENT_SRC.glob("*.md")):
        live = dest / src.name
        if not live.exists():
            drift.append(f"agents/{src.name}: MISSING in {dest}")
            continue
        want, have = _render_agent(src, frags), live.read_text()
        if want != have:
            n = len(list(difflib.unified_diff(want.splitlines(), have.splitlines())))
            drift.append(f"agents/{src.name}: HAND-EDITED ({n} diff lines)")
    return drift


def _emit_agents(dest: Path, frags: dict[str, str]) -> None:
    dest.mkdir(parents=True, exist_ok=True)
    keep = set()
    for src in sorted(AGENT_SRC.glob("*.md")):
        (dest / src.name).write_text(_render_agent(src, frags))
        keep.add(src.name)
    # Prune ONLY what we generated. An operator's own agent definition must survive — deleting a
    # hand-authored file here would be data loss, and the banner is what tells them apart.
    for stale in dest.glob("*.md"):
        if stale.name not in keep and BANNER.strip() in stale.read_text(errors="replace"):
            stale.unlink()


def render(dest: Path, skills_dest: Path | None = None, agents_dest: Path | None = None):
    dest.mkdir(parents=True, exist_ok=True)
    frags = {p.stem: p.read_text().rstrip("\n") for p in FRAG.glob("*.md")}
    if agents_dest is None:
        # Follow dest: only a render aimed at the LIVE commands dir may touch the LIVE agents
        # dir. An inspection render (`--dest /tmp/x`, or a bare `render(tmpdir)` import call)
        # used to silently overwrite ~/.claude/agents — measured live TWICE by review finders
        # on 2026-08-31 (STRATEGIC_BACKLOG promotion trigger), which is why this derives
        # instead of defaulting.
        agents_dest = AGENTS if dest.resolve() == OUT.resolve() else dest / "_agents"
    _emit_agents(agents_dest, frags)
    errs = []
    emitted: list[tuple[str, str]] = []
    for s in sorted(SRC.glob("*.md")):
        name, text = s.stem, s.read_text()

        # `name=name` binds THIS iteration's source name into the closure. The
        # call site below is immediate (same iteration), so late binding was
        # already benign — the default makes the guarantee explicit rather than
        # incidental, so a later refactor that defers the call can't misattribute
        # a render error to the wrong command.
        def sub(m, name=name, src=text):
            fr = m.group(1)
            body = frags.get(fr)
            if body is None:
                errs.append(f"{name}: unknown fragment {fr}")
                return m.group(0)
            params = dict(PARAMS.get(name, {}).get(fr, {}))
            if fr == "run-record":
                # Computed, never hand-written: the run record's two values are the command's
                # own name and its own phase count, both derivable from the source. Hand-authored
                # PARAMS for 24 commands would drift the moment a phase is added — and a wrong
                # phase count makes the pinned RUN: line lie about where the run is.
                params.setdefault("COMMAND", name)
                params.setdefault("PHASES", str(_phase_count(src)))
            # D-181/D-182 (2026-09-07): the per-command HEADLINE values above name `fanout` /
            # `set_quality` — the pool contract. While the pool is OFF by ruling every includer of
            # `subagents-core` renders ONE honest heading; the per-command values stay in PARAMS for
            # re-enable (delete this override to restore them). Outside the run-record branch on
            # purpose — review seat B, 2026-09-07: placed inside it, 20 of 20 headlines kept the pool text.
            if fr == "subagents-core" and "HEADLINE" in params:
                params["HEADLINE"] = "native seats only — the pool is OFF by ruling (D-181/D-182)"
                # the pool-independent half of a command's EXTRA renders in the LIVE paragraph;
                # `{{EXTRA}}` sits inside the <!-- POOL OFF --> comment and is dead while the pool
                # is OFF (round-5 finding: /fabrik-spec's "an EMPTY grounding is a FAILED grounding"
                # and its native tiering were invisible to the agent running it)
                params.setdefault("EXTRA_LIVE", "")
            for k, v in params.items():
                body2 = body.replace("{{" + k + "}}", v)
                body = body2
            return body

        text = re.sub(r"^\{\{include:([\w-]+)\}\}$", sub, text, flags=re.M)
        leftover = re.findall(r"\{\{(?:include:)?[A-Za-z_-]+\}\}", text)
        if leftover:
            errs.append(f"{name}: unresolved {sorted(set(leftover))}")
        # AUTO-APPENDED to every command, never hand-included in any source. Operator directive
        # 2026-08-27: a command run is the moment the machinery is exercised, so the agent running
        # it is the only witness to how it actually behaved — and a defect routed around silently
        # dies in that session's context. The duty existed in prose in BOTH constitutions and was
        # bound to no command.
        #
        # Structural, because opt-in obligations are the ones a NEW command silently ships without —
        # exactly the run-record defect (wired into 3 of 27 commands before it was made a shared
        # fragment). Appended AFTER fragment substitution so it cannot itself be shadowed, and
        # guarded so a source that also includes it explicitly does not emit it twice.
        if _CLOSE_FEEDBACK in frags and frags[_CLOSE_FEEDBACK].split("\n", 1)[0] not in text:
            text = text.rstrip("\n") + "\n\n" + frags[_CLOSE_FEEDBACK] + "\n"
        desc_raw = _description_of(
            text
        )  # captured BEFORE requoting — _emit_skill applies its own _yaml_dq
        text = _requote_command_description(text)
        # banner after frontmatter
        if text.startswith("---"):
            end = text.index("\n---", 3) + 4
            text = text[:end] + "\n" + BANNER + text[end:].lstrip("\n")
        else:
            text = BANNER + text
        (dest / s.name).write_text(text)
        emitted.append((name, desc_raw))
    if errs:  # gate BEFORE touching the skills tree — a failed render never mutates skills
        print("RENDER ERRORS:")
        for e in errs:
            print(" -", e)
        sys.exit(2)
    source_names = {n for n, _ in emitted}
    if skills_dest is not None:
        for name, desc in emitted:
            _emit_skill(name, desc, skills_dest)
    # Prune orphans (ONLY files carrying our generator banner — never a hand-authored
    # or sibling skill/command): a renamed/deleted source must not leave an invokable stale.
    # The keep-set IS the source set: a generated skill whose name is no longer a source leaves
    # through this prune (the retired orchestrator wrappers, 2026-09-05, went this way).
    keep = source_names
    for cmd in dest.glob("*.md"):
        if cmd.stem not in keep and BANNER.strip() in cmd.read_text():
            cmd.unlink()
    if skills_dest is not None:
        for sk in skills_dest.glob("*/SKILL.md"):
            if sk.parent.name not in keep and SKILL_BANNER in sk.read_text():
                shutil.rmtree(sk.parent)
    n = len(emitted)
    n_agents = len(list(AGENT_SRC.glob("*.md")))
    print(
        f"rendered {n} commands -> {dest}"
        + (f" + {n} skills -> {skills_dest}" if skills_dest else "")
        + f" + {n_agents} agents -> {agents_dest}"
    )


def check():
    with tempfile.TemporaryDirectory() as td:
        tmp = Path(td)
        tmp_sk = tmp / "_skills"
        tmp_ag = tmp / "_agents"
        render(tmp, tmp_sk, agents_dest=tmp_ag)
        # Agent definitions are part of the corpus now: a hand-edit on the box must show up here,
        # or the repo sources are merely FIRST rather than canonical.
        drift = list(agent_drift(AGENTS))
        # D-191: a fan-out with no dispatch step is a rule with no grader (round-2 finding)
        drift += [
            f"{n}.md: fans out without the D-191 dispatch step"
            for n in dispatch_step_gaps({f.stem: f.read_text() for f in tmp.glob("*.md")})
        ]
        for f in sorted(tmp.glob("*.md")):
            inst = OUT / f.name
            if not inst.exists():
                drift.append(f"{f.name}: MISSING in {OUT}")
                continue
            if inst.read_text() != f.read_text():
                d = list(
                    difflib.unified_diff(
                        f.read_text().splitlines(),
                        inst.read_text().splitlines(),
                        "rendered",
                        "installed",
                        lineterm="",
                    )
                )
                drift.append(f"{f.name}: HAND-EDITED ({len(d)} diff lines)")
        # every command must ALSO have an in-sync SKILL.md
        for sd in sorted(tmp_sk.glob("*/SKILL.md")):
            inst = SKILLS / sd.parent.name / "SKILL.md"
            if not inst.exists():
                drift.append(f"skills/{sd.parent.name}: MISSING SKILL.md in {SKILLS}")
                continue
            if inst.read_text() != sd.read_text():
                drift.append(f"skills/{sd.parent.name}: HAND-EDITED SKILL.md")
        # orphan detection: an installed GENERATED command/skill whose _source is gone
        # (catches a rename/delete that wasn't followed by a re-render — the prune).
        src_names = {s.stem for s in SRC.glob("*.md")}
        for cmd in sorted(OUT.glob("*.md")):
            if cmd.stem not in src_names and BANNER.strip() in cmd.read_text():
                drift.append(f"{cmd.name}: ORPHAN (generated, no _source — re-render to prune)")
        for sk in sorted(SKILLS.glob("*/SKILL.md")):
            if sk.parent.name not in src_names and SKILL_BANNER in sk.read_text():
                drift.append(
                    f"skills/{sk.parent.name}: ORPHAN (generated, no _source — re-render to prune)"
                )
        if drift:
            print("DRIFT:")
            for x in drift:
                print(" -", x)
            sys.exit(1)
        print("check OK — installed commands + skills match rendered sources")


