def _orch_phase_count(text: str) -> int:
    """`--phases` for an orchestrator doc: DISTINCT INTEGER step numbers, never a heading count.

    Three measured reasons a raw heading count lies (all from the live docs, 2026-08-18):
    * `00-trigger` has 11 `### Step` headings, but they are two mutually exclusive MODE branches
      (Step 0 + N1…N5, or Step 0 + E1…E5) — no run walks more than 6, so `--phases 11` makes the
      pinned RUN: line permanently understate progress and the total unreachable.
    * `02`/`04` carry half-steps (`Step 3.5`, `Step 1.5`) — counting them gave 5 phases for a walk
      whose `step --phase` values (integers, per command_run.py) top out at 4.
    * ettw `01R` uses `## Phase N` headings, which a Step-only regex counted as zero.
    Distinct integer parts collapse all three: N1/E1 → 1 (parallel modes overlay), 3.5 → 3
    (a half-step advances no integer phase), Phase headings count alongside Step ones.
    """
    nums = {
        int(m.group(1))
        for m in re.finditer(
            r"^#{2,4}\s+\**(?:Step|Phase)\s+[A-Za-z]?(\d+)", text, flags=re.M
        )
    }
    # ettw-00 writes every heading as `### **Step 1: …**` — without the \** tolerance it counted
    # ZERO and shipped `--phases 1` for an 8-step workflow (closing-sweep finding). And a
    # `Step 0` label needs dropping when other steps exist: `command_run.py step --phase 0`
    # clamps to 1, so counting 0 as its own phase makes the final total unreachable and the
    # pinned RUN: line reads finished-minus-one forever.
    if 0 in nums and len(nums) > 1:
        nums.discard(0)
    return max(len(nums), 1)


def _render_orch_wrapper(name: str) -> str:
    """The generated wrapper: pointer to the canonical doc + the run-record block.

    The run record is the whole reason these are generated now — the wrapper is what loads at
    invocation, so the record's COMMAND/PHASES ride it, computed from the doc (a hand-written
    phase count drifts the moment a step is added, and a wrong count makes the pinned RUN:
    line lie about where the run is)."""
    doc_rel, desc = ORCH_SOURCES[name]
    if len(desc) > 1024:
        raise SystemExit(
            f"_render_orch_wrapper: {name}: description is {len(desc)} chars, over the "
            "1024-char skill limit — trim the ORCH_SOURCES entry"
        )
    doc = ROOT.parent / doc_rel
    body = doc.read_text(encoding="utf-8")  # missing doc = render error, never a silent skip
    record = (FRAG / "run-record.md").read_text(encoding="utf-8").rstrip("\n")
    record = record.replace("{{COMMAND}}", name).replace(
        "{{PHASES}}", str(_orch_phase_count(body))
    )
    leftover = re.findall(r"\{\{[\w:-]+\}\}", record)
    if leftover:
        # a token added to the fragment but not substituted here would ship literally into all
        # 17 wrappers — the same guard render() has for command bodies, which this path bypassed
        raise SystemExit(f"_render_orch_wrapper: {name}: unresolved {sorted(set(leftover))}")
    return (
        f"---\n"
        f"name: {name}\n"
        f'description: "{_yaml_dq(desc)}"\n'
        f"---\n\n"
        f"{SKILL_BANNER}\n"
        f"<!-- source-of-truth for THIS wrapper: /opt/fabrik/{doc_rel} + the ORCH_SOURCES table "
        f"in assemble_commands.py (NOT _sources/ — the banner above is the generic generator "
        f"stamp; orchestrator wrappers render from the canonical doc named below) -->\n\n"
        f"# {name} (thin wrapper → source-of-truth in /opt/fabrik)\n\n"
        f"Read the command specification at:\n\n"
        f"`/opt/fabrik/{doc_rel}`\n\n"
        f"Follow it **exactly** as written. It is the canonical, git-tracked source; this\n"
        f"skill is only the Traycer-invocation shim. Do not improvise beyond the spec.\n\n"
        f"{record}\n"
    )


def _emit_orch_wrappers(skills_dest: Path, update_tracked: bool) -> None:
    """Write the generated orchestrator wrappers; mirror to the tracked tree on real installs.

    `update_tracked` is False for `--check`'s temp render — a read-only check must never
    mutate docs/orchestrator/_traycer-skills/."""
    for name in ORCH_SOURCES:
        body = _render_orch_wrapper(name)
        d = skills_dest / name
        d.mkdir(parents=True, exist_ok=True)
        (d / "SKILL.md").write_text(body)
        if update_tracked:
            t = TRAYCER_SKILLS / name
            t.mkdir(parents=True, exist_ok=True)
            (t / "SKILL.md").write_text(body)


def _emit_skill(name: str, description: str, skills_dest: Path) -> None:
    """Write a thin SKILL.md wrapper so every command is ALSO a model-invokable
    skill. Triggering lives in `description`; the body redirects to the canonical
    rendered command (single source of truth) and names the next pipeline step."""
    nxt = NEXT.get(name, "(no defined successor — this command is terminal or standalone).")
    desc = " ".join(description.split())  # collapse newlines for YAML one-line
    if desc and desc[-1] not in ".!?":  # avoid a run-on before "Invoke for"
        desc += "."
    # BOTH desc and nxt are interpolated into a YAML double-quoted scalar — escape both.
    desc_yaml = _yaml_dq(desc)
    nxt_yaml = _yaml_dq(nxt)
    full_desc = f"{desc} Invoke for /{name}, or when a task matches this stage. NEXT: {nxt}"
    if len(full_desc) > 1024:
        raise SystemExit(
            f"_emit_skill: {name}: composed skill description is {len(full_desc)} chars, "
            f"exceeds the 1024-char limit — trim the source description or the NEXT entry"
        )
    body = (
        f"---\n"
        f"name: {name}\n"
        f'description: "{desc_yaml} Invoke for /{name}, or when a task matches this stage. '
        f'NEXT: {nxt_yaml}"\n'
        f"---\n\n"
        f"{SKILL_BANNER}\n\n"
        f"# /{name}\n\n"
        f"Run the command **`/{name}`** — its full canonical methodology is in "
        f"`~/.claude/commands/{name}.md` (rendered from "
        f"`/opt/fabrik/commands/_sources/{name}.md`; edit the source, never this "
        f"wrapper). Follow that file exactly.\n\n"
        f"**Next in the pipeline:** {nxt}\n"
    )
    d = skills_dest / name
    d.mkdir(parents=True, exist_ok=True)
    (d / "SKILL.md").write_text(body)

