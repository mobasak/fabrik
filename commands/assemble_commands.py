# The D-191 grader: a command whose text fans out (a seat per unit, "all in one message") must carry
# the dispatch step — the fragment's or the short banner's. Measured on the 36 rendered commands
# before it shipped: 27 fan out and carry it, 3 fanned out without it (design-review, rivals,
# upstream — the rule's only seat instruction there was the one D-191 overturned), 6 are serial by
# design and match neither; 0 false positives.
_FANOUT_RE = re.compile(
    r"((?:seats? per |per (?:unit|screen|rival|claim|persona|lens|surface|dependency|fact|file"
    r"|flow-bundle|epic|pack|doc)\b)[^.]{0,80}(?:single|one|ONE) message|dispatch(?:ed|es)?[^.]{0,60}"
    r"in (?:a )?(?:single|ONE|one) message|(?:seats?|subagents?|agents?|finders?)[^.]{0,60}"
    r"\bin parallel\b)",
    re.I,
)
_DISPATCH_STEP_RE = re.compile(r"THE DISPATCH STEP \(D-191|Dispatch step \(D-191\)", re.I)


_HTML_COMMENT_RE = re.compile(r"<!--.*?-->", re.S)


def dispatch_step_gaps(rendered: dict[str, str]) -> list[str]:
    """Names of rendered commands that fan out and do not carry the D-191 dispatch step — judged
    on the LIVE text: `<!-- POOL OFF -->` blocks are stripped first, so a step that survives only
    inside a comment cannot satisfy the grader (round-3 finding; the corpus keeps the pool-era
    paragraphs in exactly such comments for re-enable)."""
    out = []
    for name, text in rendered.items():
        live = _HTML_COMMENT_RE.sub("", text)
        if _FANOUT_RE.search(live) and not _DISPATCH_STEP_RE.search(live):
            out.append(name)
    return sorted(out)


